@dataclass
class GrandStrip:
    model: PatchModel | None
    width: int
    periodic_y: bool
    states: np.ndarray
    n_column: np.ndarray
    nondirectional: np.ndarray
    directional: np.ndarray
    n_step: np.ndarray

    @classmethod
    def build(
        cls, model: PatchModel | None, width: int, periodic_y: bool = True
    ) -> "GrandStrip":
        """Build all column observables, with local state 0 denoting vacancy."""
        q = 1 if model is None else model.q
        states = np.asarray(
            list(itertools.product(range(q + 1), repeat=width)), dtype=np.int16
        )
        occupied = states > 0
        n_column = np.sum(occupied, axis=1).astype(np.int16)

        vertical_pairs = (
            tuple((j, (j + 1) % width) for j in range(width))
            if periodic_y
            else tuple((j, j + 1) for j in range(width - 1))
        )
        vertical_occ = np.asarray(
            [sum(int(row[j] and row[k]) for j, k in vertical_pairs)
             for row in occupied],
            dtype=np.int16,
        )
        horizontal_occ = np.sum(
            occupied[:, None, :] & occupied[None, :, :], axis=2
        )

        if model is None:
            vertical_dir = np.zeros(len(states), dtype=np.int16)
            horizontal_dir = np.zeros((len(states), len(states)), dtype=np.int16)
        else:
            north = np.asarray((0,) + model.north, dtype=np.int8)
            east = np.asarray((0,) + model.east, dtype=np.int8)
            south = np.asarray((0,) + model.south, dtype=np.int8)
            west = np.asarray((0,) + model.west, dtype=np.int8)
            vertical_dir = np.asarray(
                [sum(int(south[row[j]] and north[row[k]])
                     for j, k in vertical_pairs)
                 for row in states],
                dtype=np.int16,
            )
            horizontal_dir = np.sum(
                east[states[:, None, :]] * west[states[None, :, :]], axis=2
            ).astype(np.int16)

        nondirectional = horizontal_occ.astype(float) + 0.5 * (
            vertical_occ[:, None] + vertical_occ[None, :]
        )
        directional = horizontal_dir.astype(float) + 0.5 * (
            vertical_dir[:, None] + vertical_dir[None, :]
        )
        n_step = 0.5 * (n_column[:, None] + n_column[None, :])
        return cls(
            model=model,
            width=width,
            periodic_y=periodic_y,
            states=states,
            n_column=n_column,
            nondirectional=nondirectional,
            directional=directional,
            n_step=n_step,
        )

    @property
    def size(self) -> int:
        return len(self.states)

    def solve(self, eps_nd: float, eps_d: float, mu: float) -> dict[str, float]:
        """Solve the positive transfer matrix and all analytic derivatives."""
        exponent = (
            float(eps_nd) * self.nondirectional
            + float(eps_d) * self.directional
            - float(mu) * self.n_step
        )
        shift = float(np.max(exponent))
        transfer = np.exp(exponent - shift)
        values, left_vectors, right_vectors = eig(
            transfer, left=True, right=True, check_finite=False
        )
        index = int(np.argmax(values.real))
        lam_scaled = float(np.real(values[index]))
        if lam_scaled <= 0.0 or abs(np.imag(values[index])) > 1.0e-9:
            raise RuntimeError(f"invalid Perron root {values[index]}")
        left = np.real_if_close(left_vectors[:, index]).astype(float)
        right = np.real_if_close(right_vectors[:, index]).astype(float)
        if float(np.dot(left, right)) < 0.0:
            left = -left
        overlap = float(np.dot(left, right))
        denominator = lam_scaled * overlap

        def expectation(observable: np.ndarray) -> float:
            return float(
                np.dot(left, (observable * transfer) @ right) / denominator
            )

        contacts_column = expectation(self.nondirectional)
        directional_column = expectation(self.directional)
        particles_column = expectation(self.n_step)
        log_lambda = shift + math.log(lam_scaled)

        rho = particles_column / self.width
        contacts = contacts_column / self.width
        bonds = directional_column / self.width
        entropy = (
            log_lambda
            - eps_nd * contacts_column
            - eps_d * directional_column
            + mu * particles_column
        ) / self.width
        beta_u = -eps_nd * contacts - eps_d * bonds
        beta_f = -log_lambda / self.width - mu * rho
        identity_error = abs(entropy - (beta_u - beta_f))
        if identity_error > 2.0e-10:
            raise AssertionError("thermodynamic identity failed")

        # Stationary transfer-chain transition probabilities:
        # P_ij = T_ij r_j/(lambda r_i), pi_i = l_i r_i/(l.r).
        # Eigenvector signs are arbitrary but the Perron vectors are one-signed.
        if float(np.sum(right)) < 0.0:
            right = -right
        if float(np.sum(left)) < 0.0:
            left = -left
        stationary = left * right
        stationary /= float(np.sum(stationary))
        transition = (
            transfer * right[None, :] / (lam_scaled * right[:, None])
        )
        transition /= np.sum(transition, axis=1, keepdims=True)
        if np.min(transition) < -1.0e-13 or np.min(stationary) < -1.0e-13:
            raise AssertionError("invalid Perron Markov chain")

        log_transition = np.log(transition)
        entropy_rate_column = -float(
            np.sum(stationary[:, None] * transition * log_transition)
        )
        if abs(entropy_rate_column / self.width - entropy) > 3.0e-10:
            raise AssertionError("transfer-chain entropy rate mismatch")

        occupied = self.states > 0
        powers = (1 << np.arange(self.width, dtype=np.int64))
        occupancy_symbols = np.sum(occupied * powers[None, :], axis=1)
        n_symbols = 1 << self.width
        occupancy_probability = np.zeros((self.size, n_symbols), dtype=float)
        for symbol in range(n_symbols):
            occupancy_probability[:, symbol] = np.sum(
                transition[:, occupancy_symbols == symbol], axis=1
            )
        positive = occupancy_probability > 0.0
        occupancy_entropy_column = -float(
            np.sum(
                stationary[:, None]
                * np.where(
                    positive,
                    occupancy_probability
                    * np.log(np.where(positive, occupancy_probability, 1.0)),
                    0.0,
                )
            )
        )
        internal_entropy_column = entropy_rate_column - occupancy_entropy_column
        if internal_entropy_column < -3.0e-11:
            raise AssertionError("negative conditional internal entropy")
        internal_entropy_column = max(0.0, internal_entropy_column)
        internal_entropy_particle = internal_entropy_column / particles_column

        return {
            "log_lambda": log_lambda,
            "rho": rho,
            "contacts_per_site": contacts,
            "directional_bonds_per_site": bonds,
            "entropy_per_site": entropy,
            "beta_u_per_site": beta_u,
            "beta_f_per_site": beta_f,
            "occupancy_conditional_entropy_per_site": (
                occupancy_entropy_column / self.width
            ),
            "internal_conditional_entropy_per_site": (
                internal_entropy_column / self.width
            ),
            "internal_conditional_entropy_per_particle": (
                internal_entropy_particle
            ),
            "dloglambda_deps_nd": contacts_column,
            "dloglambda_deps_d": directional_column,
            "dloglambda_dmu": -particles_column,
        }


def direct_counts(
    strip: GrandStrip, left_index: int, right_index: int
) -> tuple[int, int, int, int, int]:
    """Independently recount column/edge observables with explicit loops."""
    left = strip.states[left_index]
    right = strip.states[right_index]
    n_left = sum(int(state > 0) for state in left)
    vertical_pairs = (
        tuple((j, (j + 1) % strip.width) for j in range(strip.width))
        if strip.periodic_y
        else tuple((j, j + 1) for j in range(strip.width - 1))
    )
    v_occ = sum(int(left[j] > 0 and left[k] > 0) for j, k in vertical_pairs)
    h_occ = sum(int(a > 0 and b > 0) for a, b in zip(left, right))
    if strip.model is None:
        return n_left, v_occ, h_occ, 0, 0
    model = strip.model
    north = (0,) + model.north
    east = (0,) + model.east
    south = (0,) + model.south
    west = (0,) + model.west
    v_dir = sum(int(south[left[j]] and north[left[k]])
                for j, k in vertical_pairs)
    h_dir = sum(int(east[a] and west[b]) for a, b in zip(left, right))
    return n_left, v_occ, h_occ, v_dir, h_dir


def validate_strip(strip: GrandStrip) -> list[str]:
    """Exhaustively check all state/edge counts and analytic derivatives."""
    for i in range(strip.size):
        n_i, v_occ_i, _, v_dir_i, _ = direct_counts(strip, i, i)
        if n_i != int(strip.n_column[i]):
            raise AssertionError("column occupancy mismatch")
        for j in range(strip.size):
            n_j, v_occ_j, h_occ, v_dir_j, h_dir = direct_counts(strip, j, i)
            # direct_counts(j,i) gives j as left and i as right.
            expected_nd = h_occ + 0.5 * (v_occ_j + v_occ_i)
            expected_d = h_dir + 0.5 * (v_dir_j + v_dir_i)
            if expected_nd != strip.nondirectional[j, i]:
                raise AssertionError("nondirectional count mismatch")
            if expected_d != strip.directional[j, i]:
                raise AssertionError("directional count mismatch")

    # Analytic derivatives from Perron vectors versus centered differences.
    a, d, mu = 1.31, 1.17, 4.63
    base = strip.solve(a, d, mu)
    delta = 1.0e-6
    checks = (
        ("eps_nd", (strip.solve(a + delta, d, mu)["log_lambda"]
                    - strip.solve(a - delta, d, mu)["log_lambda"])
         / (2.0 * delta), base["dloglambda_deps_nd"]),
        ("eps_d", (strip.solve(a, d + delta, mu)["log_lambda"]
                   - strip.solve(a, d - delta, mu)["log_lambda"])
         / (2.0 * delta), base["dloglambda_deps_d"]),
        ("mu", (strip.solve(a, d, mu + delta)["log_lambda"]
                - strip.solve(a, d, mu - delta)["log_lambda"])
         / (2.0 * delta), base["dloglambda_dmu"]),
    )
    messages = []
    for name, finite_difference, analytic in checks:
        error = abs(finite_difference - analytic)
        if error > 5.0e-7 * max(1.0, abs(analytic)):
            raise AssertionError(f"{name} derivative mismatch")
        messages.append(
            f"{('lattice-gas' if strip.model is None else strip.model.name):11s} "
            f"W={strip.width}: dlnlambda/d{name} FD error={error:.3e}"
        )
    return messages


def compare_point(
    model: PatchModel,
    width: int,
    full_strip: GrandStrip,
    point: dict[str, object],
) -> dict[str, object]:
    eps_nd = float(point["eps_nd"])
    eps_d = float(point["eps_d"])
    mu = float(point["mu"])
    full = full_strip.solve(eps_nd, eps_d, mu)
    s_internal_particle = full["internal_conditional_entropy_per_particle"]

    s_isolated = math.log(model.q)
    error_avg = abs(s_internal_particle)
    error_isolated = abs(s_isolated - s_internal_particle)

    return {
        "model": model.name,
        "W": width,
        "point_label": point["label"],
        "eps_nd": eps_nd,
        "eps_d": eps_d,
        "mu_critical_input": mu,
        "rho_exact_strip": full["rho"],
        "contacts_per_site_exact": full["contacts_per_site"],
        "directional_bonds_per_site_exact": full["directional_bonds_per_site"],
        "s_total_exact_per_site": full["entropy_per_site"],
        "s_occupancy_conditional_per_site": (
            full["occupancy_conditional_entropy_per_site"]
        ),
        "s_internal_conditional_per_site": (
            full["internal_conditional_entropy_per_site"]
        ),
        "s_internal_exact_per_particle": s_internal_particle,
        "s_internal_avgE_per_particle": 0.0,
        "s_internal_isolatedZ_per_particle": s_isolated,
        "abs_error_avgE": error_avg,
        "abs_error_isolatedZ": error_isolated,
        "closer_closure": "avgE" if error_avg < error_isolated else (
            "isolated-Z" if error_isolated < error_avg else "equal"
        ),
        "critical_input_status": point["critical_input_status"],
        "source": point["source"],
    }


def write_csv(path: Path, rows: list[dict[str, object]]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def interpolated_crossovers(
    full_strips: dict[tuple[str, int], GrandStrip]
) -> list[dict[str, object]]:
    """Find switches along piecewise-linear interpolation of logged triples."""
    rows: list[dict[str, object]] = []
    for model in MODELS:
        points = CRITICAL_POINTS[model.name]
        target = 0.5 * math.log(model.q)
        for width in (3, 4):
            strip = full_strips[(model.name, width)]
            found: dict[str, object] | None = None
            for left, right in zip(points[:-1], points[1:]):
                d0, d1 = float(left["eps_d"]), float(right["eps_d"])

                def parameters(eps_d: float) -> tuple[float, float]:
                    fraction = (eps_d - d0) / (d1 - d0)
                    eps_nd = float(left["eps_nd"]) + fraction * (
                        float(right["eps_nd"]) - float(left["eps_nd"])
                    )
                    mu = float(left["mu"]) + fraction * (
                        float(right["mu"]) - float(left["mu"])
                    )
                    return eps_nd, mu

                def residual(eps_d: float) -> float:
                    eps_nd, mu = parameters(eps_d)
                    return (
                        strip.solve(eps_nd, eps_d, mu)[
                            "internal_conditional_entropy_per_particle"
                        ]
                        - target
                    )

                f0, f1 = residual(d0), residual(d1)
                if f0 == 0.0 or f0 * f1 <= 0.0:
                    root = d0 if f0 == 0.0 else float(
                        brentq(residual, d0, d1, xtol=2.0e-12)
                    )
                    eps_nd_root, mu_root = parameters(root)
                    bracket_statuses = {
                        str(left["critical_input_status"]),
                        str(right["critical_input_status"]),
                    }
                    if bracket_statuses <= {
                        "exact anchor", "logged MC + FSS-checked"
                    }:
                        status = "interpolation between FSS-checked logged points"
                    else:
                        status = "interpolation between logged MC critical-line points"
                    found = {
                        "model": model.name,
                        "W": width,
                        "target_entropy_per_particle": target,
                        "eps_d_crossover": root,
                        "eps_nd_interpolated": eps_nd_root,
                        "mu_interpolated": mu_root,
                        "bracket_eps_d_low": d0,
                        "bracket_eps_d_high": d1,
                        "status": status,
                    }
                    break
            if found is None:
                found = {
                    "model": model.name,
                    "W": width,
                    "target_entropy_per_particle": target,
                    "eps_d_crossover": "not reached",
                    "eps_nd_interpolated": "",
                    "mu_interpolated": "",
                    "bracket_eps_d_low": "",
                    "bracket_eps_d_high": "",
                    "status": f"not reached through eps_d={float(points[-1]['eps_d']):.2f}",
                }
            rows.append(found)
    return rows


