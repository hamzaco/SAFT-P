@dataclass(frozen=True)
class PatchModel:
    name: str
    labels: tuple[str, ...]
    north: tuple[int, ...]
    east: tuple[int, ...]
    south: tuple[int, ...]
    west: tuple[int, ...]

    @property
    def q(self) -> int:
        return len(self.labels)


