#!/usr/bin/env python3
"""Exact strip benchmark of avgE and isolated-Z at critical state points.

This extends ``exact_strip_entropy.py`` by adding vacancies, the nondirectional
contact attraction, and the manuscript's positive occupancy cost ``mu``.  The
full orientational model is solved exactly on infinite W=3 and W=4 strips.

The exact Gibbs measure generated by the Perron vectors is a stationary Markov
chain of columns.  We decompose its entropy rate exactly as

    H(C'|C) = H(O'|C) + H(R'|C,O'),

where O' is the occupancy pattern of the new column and R' its occupied-site
orientations.  The second term is a nonnegative, environment-conditioned
internal entropy.  Per occupied particle it is compared with avgE (zero) and
isolated-Z (ln(q)).
"""

