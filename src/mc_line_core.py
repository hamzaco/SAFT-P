@dataclass
class SweepConfig:
    # --- what to run ------------------------------------------------------
    system: str = "l"
    L: int = 10
    seed: int = 0

    # segment of the critical line: eps_d from eps_sp_start to eps_sp_end,
    # inclusive of the end, in steps of eps_sp_step.
    eps_sp_start: float = 0.0
    eps_sp_end: float = 0.4
    eps_sp_step: float = 0.02

    # anchor at eps_sp_start.  For a segment starting at eps_d=0 leave these
    # None and the exact lattice-gas values are used.
    eps_ns0: Optional[float] = None
    mu0: Optional[float] = None
    s0: Optional[float] = None        # field mixing; None -> refit each step

    # --- statistics -------------------------------------------------------
    # steps(L) = sweeps_ref * (L/L_ref)^z * L^2
    sweeps_ref: float = 6.0e6
    L_ref: int = 10
    z_exponent: float = 2.17
    n_replicas: int = 8
    n_workers: int = 0                # 0 -> n_replicas
    samples_per_replica: int = 6000
    burn_frac: float = 0.10
    scout_frac: float = 0.08          # 1.0 reproduces the notebook exactly
    scout_burn_frac: float = 0.40
    max_blocks: int = 10_000

    # --- estimator knobs (notebook values) --------------------------------
    dilute_window: Tuple[float, float] = (0.00, 0.40)
    dense_window: Tuple[float, float] = (0.60, 1.00)
    scout_step0: float = 0.004
    scout_tol: float = 1e-1
    ess_frac: float = 0.40
    sigma_x: float = 0.03
    r_penalty: float = 1e-1
    w_asym: float = 2.0
    mu_reweight_step0: float = 1e-4
    mu_reweight_tol: float = 1e-2
    rho_bins: int = 200

    # box for the (eps_nd, mu) reweighting optimiser.  The notebook hard-codes
    # +-0.02, which is matched to its eps_d step of 0.02.  Scale with the step
    # so a coarser sweep is not silently clipped at the bound.
    opt_halfwidth_per_step: float = 1.0

    # --- relocation at fixed eps_d ---------------------------------------
    # The notebook's loop opens with eps_sp == eps_sp_prev, i.e. a pass with
    # ZERO displacement in eps_d that just re-asks "is this still the critical
    # point?".  At larger L that is the single most informative thing you can
    # run: it says whether the logged L=10 anchor is a critical point at this
    # L at all, and whether the chains tunnel there, before any sweep time is
    # spent.  It is also the one case where L-BFGS-B is useless -- with
    # d(eps_d)=0 there is no displacement to put it on the steep flank, and it
    # terminates at its starting point (mc_fss FINDINGS 4.1) -- so this pass
    # always uses the grid scan regardless of scan_fallback.
    relocate_first: bool = False
    # Scan half-width in eps_nd.  This used to be 0.08 scaled as L_ref/L, on
    # the argument that the ESS-usable range narrows with L (the log-weights
    # carry C ~ L^2).  That was the wrong knob: the window shrank as 1/L while
    # the displacement it has to contain does not.  Measured at eps_d = 1.8,
    # bent: eps_nd,c(20) sits at or below 1.3131, i.e. >= 0.040 below the L=10
    # anchor -- already outside the +-0.0267 window that L_ref/L scaling gave
    # L=30, which is why L=30 returned JS = 0.145 and no minimum.  So: scan
    # WIDE, and let the ESS floor below decide which part of the window is
    # usable, rather than guessing the range in advance.
    relocate_halfwidth: float = 0.15
    relocate_scale_with_L: bool = False
    relocate_mu_halfwidth: float = 0.05
    # A grid point is only eligible to be the minimum if ESS/n is at least
    # this.  Without it a wide window can pick its minimum out of the noise in
    # the ESS-dead tail.
    relocate_ess_floor: float = 0.15
    # "equal-area" pins mu to the balanced-basin value at each eps_nd.
    # "free" restores the old behaviour of letting JS pick mu, which put the
    # located point off coexistence and manufactured an apparent asymmetry.
    scan_mu_mode: str = "equal-area"
    relocate_n_eps: int = 121
    relocate_n_mu: int = 51
    # Store the JS(eps_nd) profile, the s profile, and the resampled (rho, u)
    # for every relocation pass.  Costs seconds and a few hundred kB, and is
    # the only way to tell "the minimum is outside the window" from "there is
    # no minimum" after the fact.
    store_diagnostics: bool = True
    s_profile_lo: float = -1.0
    s_profile_hi: float = 1.0
    s_profile_n: int = 161

    # --- the mixed-field fit ----------------------------------------------
    # "lbfgs" is the notebook's call verbatim.  It optimises a KDE-of-a-comb
    # objective with a default finite-difference step of 1e-8, and at small L
    # -- where rho has only L^2+1 attainable levels, so x is a comb rather
    # than a continuum -- that gradient is noise and the optimiser can walk
    # uphill to its own bound.  Observed directly at L=10: it returned
    # s = +5.00000 (the bound) at objective 0.846, while the grid minimum of
    # the SAME objective sits at s = -0.325, objective 0.207.  At L=20 the
    # fit and the grid agree to four decimals.
    # "auto" keeps the notebook's optimiser and only intervenes when it lands
    # on a bound, which costs nothing in the healthy case.
    s_estimator: str = "auto"          # lbfgs | auto | grid
    s_bound: float = 5.0
    s_guard_n: int = 81
    # sigma(M) must stay at least this fraction of sigma(rho): cuts the search
    # at the rho/u collinearity singularity.
    s_degeneracy_frac: float = 0.5
    # if the objective varies by less than this *relative* amount over the
    # admissible branch, s is not identifiable from the data and the fitted
    # value is noise.
    s_identifiable_span: float = 0.05
    # used when the fit objective has no interior minimum on the physical
    # branch.  0.0 means "pure density order parameter, M = rho", which is
    # what the logged trace values (|s| ~ 0.01) are indistinguishable from.
    s_fallback: float = 0.0

    # --- robustness -------------------------------------------------------
    scan_fallback: bool = False
    stall_tol: float = 1e-9
    max_abs_eps_step: float = 0.10    # reject an implausible jump in eps_nd
    min_crossings_warn: int = 1

    # --- bookkeeping ------------------------------------------------------
    init_mode: str = "middle"
    beta: float = 1.0
    ising_cache: Optional[str] = None
    checkpoint: Optional[str] = None
    archive_raw: bool = False
    verbose_inner: bool = False

    def steps_for(self, L=None):
        L = self.L if L is None else L
        sweeps = self.sweeps_ref * (float(L) / float(self.L_ref)) ** self.z_exponent
        return int(round(sweeps * L * L))

    def eps_sp_grid(self):
        """Targets for the continuation loop.

        With relocate_first, the first target equals eps_sp_start -- a
        zero-displacement pass -- which is exactly the notebook's first loop
        iteration.  Without it the grid starts one step in, since that pass
        costs a full chain and moves nothing when the anchor is already good.
        """
        n = int(round((self.eps_sp_end - self.eps_sp_start) / self.eps_sp_step))
        n = max(n, 0)
        g = self.eps_sp_start + self.eps_sp_step * np.arange(1, n + 1)
        if self.relocate_first:
            g = np.concatenate([[self.eps_sp_start], g])
        return g


# ----------------------------------------------------------------------------
# the driver: one segment of the critical line
# ----------------------------------------------------------------------------
def _ckpt_fingerprint(cfg: SweepConfig):
    """Everything about cfg that changes the NUMBERS.

    A checkpoint carrying a different fingerprint is not a resumable state, it
    is a different calculation.  Resuming across one silently returns the old
    answer -- which is exactly what happens after FORCE=1 overwrites the .npz
    but leaves ck_*.json in place: the grid is already exhausted, the loop body
    never runs, and the stale points are written straight back out.
    """
    keys = ("system", "L", "seed", "eps_sp_start", "eps_sp_end",
            "eps_sp_step", "eps_ns0", "mu0", "s0", "sweeps_ref", "L_ref",
            "z_exponent", "n_replicas", "samples_per_replica", "burn_frac",
            "scout_frac", "scout_burn_frac", "relocate_first",
            "relocate_halfwidth", "relocate_scale_with_L",
            "relocate_ess_floor", "scan_mu_mode", "s_estimator", "init_mode",
            "beta")
    return {k: getattr(cfg, k) for k in keys}


def run_segment(cfg: SweepConfig, verbose=True):
    """Walk eps_d from cfg.eps_sp_start to cfg.eps_sp_end at fixed L.

    One iteration reproduces one pass of the notebook's `for eps_sp in eps_sps`
    loop:

      1. equal-area mu at the CURRENT (eps_ns, eps_sp_prev)     [short chains]
      2. production chain at that mu                            [full length]
      3. mu* by reweighting in mu
      4. resample at mu*, fit the mixed field (s, r)
      5. reweight (eps_ns, mu) from eps_sp_prev to eps_sp, minimising JS
      6. record, advance eps_sp_prev
    """
    import multiprocessing as mp

    sysdef = SYSTEMS[cfg.system]
    species = get_species_list_ind(sysdef["species"])
    n_species = len(species)
    empty_index = n_species - 1
    species_mu_indices = np.arange(n_species - 1, dtype=np.int64)

    eps_ns0, mu0 = lattice_gas_anchor(cfg.system)
    eps_ns = float(cfg.eps_ns0) if cfg.eps_ns0 is not None else eps_ns0
    mu = float(cfg.mu0) if cfg.mu0 is not None else mu0
    eps_sp_prev = float(cfg.eps_sp_start)
    s_ref = cfg.s0

    grid = cfg.eps_sp_grid()
    points: List[Dict] = []
    start_index = 0

    # --- resume from checkpoint ------------------------------------------
    if cfg.checkpoint and os.path.exists(cfg.checkpoint):
        with open(cfg.checkpoint) as fh:
            st = json.load(fh)

        fp_now = _ckpt_fingerprint(cfg)
        fp_old = st.get("fingerprint")
        ver_old = st.get("code_version", 0)
        if ver_old != MC_LINE_VERSION or fp_old != fp_now:
            diffs = []
            if ver_old != MC_LINE_VERSION:
                diffs.append(f"code_version {ver_old} -> {MC_LINE_VERSION}")
            for k, v in fp_now.items():
                if fp_old is None or fp_old.get(k) != v:
                    old = "<absent>" if fp_old is None else fp_old.get(k)
                    diffs.append(f"{k}: {old!r} -> {v!r}")
            raise SystemExit(
                "\nREFUSING TO RESUME: the checkpoint\n"
                f"    {cfg.checkpoint}\n"
                "was written by a different calculation, so resuming it would "
                "return the older\nanswer rather than recomputing.  What "
                "changed:\n"
                + "".join(f"    {d}\n" for d in diffs[:12])
                + "\nDelete the checkpoint to start this one fresh:\n"
                f"    rm -f {cfg.checkpoint}\n")

        points = st.get("points", [])
        eps_ns = float(st["eps_ns"])
        mu = float(st["mu"])
        eps_sp_prev = float(st["eps_sp_prev"])
        s_ref = st.get("s_ref", s_ref)
        start_index = int(st.get("next_index", len(points)))
        if verbose:
            print(f"[resume] {cfg.checkpoint}: {len(points)} steps done, "
                  f"eps_d_prev={eps_sp_prev:.4f} eps_nd={eps_ns:.6f} "
                  f"mu={mu:.6f}", flush=True)

    if verbose:
        print(f"[setup] system={cfg.system} L={cfg.L} seed={cfg.seed}",
              flush=True)
        print(f"[setup] n_species={n_species} "
              f"patches={[list(map(int, p.patches)) for p in species]}",
              flush=True)
        print(f"[setup] segment eps_d {cfg.eps_sp_start:.4f} -> "
              f"{cfg.eps_sp_end:.4f} step {cfg.eps_sp_step:.4f} "
              f"({grid.size} steps)", flush=True)
        print(f"[setup] anchor eps_nd={eps_ns:.6f} mu={mu:.6f} "
              f"s={'refit' if s_ref is None else f'{s_ref:.5f}'}", flush=True)

    centers_ref, edges_ref, P_smooth = ising_reference(
        cache_path=cfg.ising_cache, verbose=verbose)
    P_ref = P_smooth / _trapz(P_smooth, centers_ref)

    rng = np.random.default_rng(cfg.seed * 7919 + 17)
    rng_shuffle = np.random.default_rng(cfg.seed * 104729 + 3)
    rng_resample = np.random.default_rng(cfg.seed * 6151 + 11)
    lattices = make_lattices(species, cfg.L, cfg.init_mode, rng)

    steps_prod = cfg.steps_for()
    steps_scout = max(int(steps_prod * cfg.scout_frac), 10_000)

    def _plan(steps):
        return dict(steps=int(steps),
                    snap=max(int(steps) // cfg.samples_per_replica, 1),
                    block=max(1000, int(steps) // cfg.max_blocks))

    P_prod, P_scout = _plan(steps_prod), _plan(steps_scout)
    buf = cfg.samples_per_replica + 16
    n_total = cfg.n_replicas * int(cfg.samples_per_replica * (1 - cfg.burn_frac))
    ess_min = cfg.ess_frac * n_total

    if verbose:
        print(f"[setup] steps/replica  production={steps_prod:.3e} "
              f"({steps_prod / cfg.L ** 2:.3e} sweeps)  "
              f"scout={steps_scout:.3e}", flush=True)
        print(f"[setup] replicas={cfg.n_replicas} "
              f"samples/replica={cfg.samples_per_replica} "
              f"n_total~{n_total} ess_min={ess_min:.0f}", flush=True)
        print(f"[setup] snapshot_interval={P_prod['snap']} "
              f"block_size={P_prod['block']} buffer={buf}", flush=True)

    payload = dict(species=species, species_mu_indices=species_mu_indices,
                   empty_index=empty_index, beta=cfg.beta)
    nw = cfg.n_workers or cfg.n_replicas
    ctx = mp.get_context("fork")
    pool = ctx.Pool(processes=int(nw), initializer=_worker_init,
                    initargs=(payload, cfg.seed + 1))
    if verbose:
        print(f"[setup] worker pool: {nw} processes (fork, numba reseeded)",
              flush=True)

    call_counter = [0]

    def _sim(eps_ns_cur, eps_sp_cur, mu_trial, plan, burn, keep_raw=False):
        call_counter[0] += 1
        return build_data_mu(
            pool, lattices, species, species_mu_indices,
            eps_ns_cur, eps_sp_cur, mu_trial, cfg.beta,
            plan["steps"], plan["snap"], buf, plan["block"],
            cfg.n_replicas, burn, rng_shuffle, cfg.L,
            call_id=call_counter[0], keep_raw=keep_raw)

    last_raw = {}
    diag_arrays = {}
    try:
        for i in range(start_index, grid.size):
            eps_sp = float(grid[i])
            t_step = time.perf_counter()
            if verbose:
                print(f"\n=== Step {i + 1}/{grid.size}: target eps_d={eps_sp:.4f} "
                      f"(prev={eps_sp_prev:.4f})  L={cfg.L} ===", flush=True)

            # --- 1. equal-area mu, short chains --------------------------
            def simulate(mu_trial):
                return _sim(eps_ns, eps_sp_prev, mu_trial, P_scout,
                            cfg.scout_burn_frac)

            guard = find_mu_equal_areas_by_simulation(
                simulate, mu0=mu,
                dilute_window=cfg.dilute_window,
                dense_window=cfg.dense_window,
                step0=cfg.scout_step0, tol=cfg.scout_tol,
                verbose=cfg.verbose_inner or verbose)
            mu = float(guard["mu"])

            # --- 2. production chain at that mu --------------------------
            data_mu = _sim(eps_ns, eps_sp_prev, mu, P_prod, cfg.burn_frac,
                           keep_raw=cfg.archive_raw)
            diag = data_mu.diag

            rho = data_mu.rho_mu
            u = data_mu.u
            C = data_mu.C_ns
            Ca = data_mu.C_sp
            N = data_mu.N_mu

            # --- 3. mu* by reweighting in mu -----------------------------
            res_equal = equal_peak_mu_in_rho_by_reweighting(
                rho, N, mu, beta=cfg.beta,
                rho_edges=np.linspace(0.0, 1.0, cfg.rho_bins + 1),
                dilute_window=cfg.dilute_window,
                dense_window=cfg.dense_window,
                ess_min=ess_min, step0=cfg.mu_reweight_step0,
                tol=cfg.mu_reweight_tol,
                verbose=cfg.verbose_inner)
            mu_star = float(res_equal["mu_star"])
            ess_mu = float(res_equal["ess"])

            # --- 4. resample at mu*, fit the mixed field -----------------
            rw = resample_at_mu_star(data_mu, mu_star, rng=rng_resample)
            rho_r = rw["rho_mu"]
            u_r = rw["u"]
            C_r = rw["C_ns"]
            Ca_r = rw["C_sp"]
            N_r = rw["N_mu"]

            # Confine the fit to the branch of s on which M = rho - s*u is a
            # usable order parameter (see s_admissible_range).
            s_lo, s_hi, s_sing, s_sigmin = s_admissible_range(
                rho_r, u_r, frac=cfg.s_degeneracy_frac, s_bound=cfg.s_bound)
            if not np.isfinite(s_lo):
                s_lo, s_hi = -cfg.s_bound, cfg.s_bound
                print("[warn] s = 0 lies inside the rho/u degeneracy band; "
                      "the mixed-field fit is not identifiable here. "
                      "Use --s0 with the logged trace value.", flush=True)
            if cfg.s_estimator == "lbfgs":
                s_lo, s_hi = -cfg.s_bound, cfg.s_bound

            fit = fit_s_r_from_reweighted(
                rho=rho_r, u=u_r, x_ref=centers_ref, s_ref=s_ref,
                P_ref=P_ref, weights=None, L=cfg.L,
                sigma_x=cfg.sigma_x, r_penalty=cfg.r_penalty,
                w_asym=cfg.w_asym, bounds_s=(s_lo, s_hi))
            s_fit = float(fit["s"])
            r_fit = float(fit["r"])

            # Guard the mixed-field fit.  See SweepConfig.s_estimator.
            #
            # The objective is one-dimensional (r is inert), bounded, and
            # evaluated on a KDE of a comb, so a grid + local parabola is both
            # cheaper and far more robust than a quasi-Newton method with a
            # 1e-8 finite-difference step.  Measured at production sample
            # counts: an 81-point profile costs ~10 s against a 3 min (L=10)
            # to 5 h (L=30) MC step, i.e. nothing.  So run both and keep the
            # better one -- this can never be worse than the notebook.
            s_on_bound = (abs(s_fit - s_lo) < 1e-6 or abs(s_fit - s_hi) < 1e-6)
            s_rescued = False
            s_flat = False
            s_unidentified = False
            s_span = float("nan")
            s_obj_lbfgs = float("nan")
            s_obj_grid = float("nan")
            if cfg.s0 is None and cfg.s_estimator != "lbfgs":
                g_lo = max(cfg.s_profile_lo, s_lo)
                g_hi = min(cfg.s_profile_hi, s_hi)
                spg = profile_s(
                    rho_r, u_r, centers_ref, P_ref,
                    s_grid=np.linspace(g_lo, g_hi, cfg.s_guard_n),
                    sigma_x=cfg.sigma_x, r_penalty=cfg.r_penalty,
                    w_asym=cfg.w_asym)
                sg, og = spg["s_grid"], spg["obj"]
                s_span = float(np.max(og) - np.min(og))
                s_flat = bool(s_span < cfg.s_identifiable_span
                              * max(float(np.min(og)), 1e-12))
                j = int(np.argmin(og))

                # Does the objective have an INTERIOR minimum on the physical
                # branch?  If it slides to an edge instead, s is not determined
                # by these data, and "rescuing" it to the edge would be worse
                # than the runaway it replaces -- it would look converged.
                # Say so and fall back to a fixed value.
                s_unidentified = bool(j == 0 or j == sg.size - 1 or s_flat)

                if s_unidentified:
                    fallback = (float(cfg.s0) if cfg.s0 is not None
                                else float(cfg.s_fallback))
                    print(f"[s-guard] NOT IDENTIFIABLE at L={cfg.L}, "
                          f"eps_d={eps_sp:.4f}: the fit objective has no "
                          f"interior minimum on the physical branch "
                          f"[{g_lo:+.4f}, {g_hi:+.4f}] "
                          f"(min at the {'lower' if j == 0 else 'upper'} edge, "
                          f"span {s_span:.4g}).  Falling back to "
                          f"s = {fallback:+.5f}.  Pass --s0 with the logged "
                          f"trace value to make this explicit.", flush=True)
                    s_fit = fallback
                    s_rescued = True
                else:
                    s_grid_min = float(sg[j])
                    cq = np.polyfit(sg[j - 1:j + 2], og[j - 1:j + 2], 2)
                    if cq[0] > 0:
                        cand = -0.5 * cq[1] / cq[0]
                        if sg[0] <= cand <= sg[-1]:
                            s_grid_min = float(cand)
                    pair = profile_s(rho_r, u_r, centers_ref, P_ref,
                                     s_grid=np.array([s_fit, s_grid_min]),
                                     sigma_x=cfg.sigma_x,
                                     r_penalty=cfg.r_penalty,
                                     w_asym=cfg.w_asym)
                    s_obj_lbfgs = float(pair["obj"][0])
                    s_obj_grid = float(pair["obj"][1])
                    if (cfg.s_estimator == "grid"
                            or s_obj_grid < s_obj_lbfgs):
                        if verbose:
                            print(f"[s-guard] L-BFGS-B s={s_fit:+.5f} "
                                  f"(obj {s_obj_lbfgs:.5g})"
                                  f"{'  ON BOUND' if s_on_bound else ''}"
                                  f"  ->  grid s={s_grid_min:+.5f} "
                                  f"(obj {s_obj_grid:.5g})", flush=True)
                        s_rescued = bool(abs(s_grid_min - s_fit) > 1e-4)
                        s_fit = s_grid_min

            s_use = s_fit if cfg.s0 is None else float(cfg.s0)
            s_ref = s_use

            Mprime = rho_r - s_use * u_r
            Mc = float(Mprime.mean())
            lambdap = 1.0 - s_use * r_fit

            # --- 5. reweight (eps_nd, mu) from eps_sp_prev to eps_sp -----
            theta_ref = (eps_ns, eps_sp_prev, mu_star, lambdap, Mc, s_use)
            d_eps_d = float(eps_sp) - float(eps_sp_prev)
            relocating = abs(d_eps_d) < 1e-12
            curvature = float("nan")

            if relocating:
                # Zero displacement: L-BFGS-B cannot move here (the objective
                # is piecewise constant and it starts at the minimum of its own
                # starting bin), so go straight to the scan.  The window is the
                # finite-size rounding width, not the eps_d step.
                half = cfg.relocate_halfwidth
                if cfg.relocate_scale_with_L:
                    half *= float(cfg.L_ref) / float(cfg.L)
                half_mu = cfg.relocate_mu_halfwidth
                sc = scan_eps_mu_fixed_epsA_fixed_s(
                    theta_ref, eps_sp, rho_r, u_r, C_r, Ca_r, N_r,
                    edges_ref, P_ref,
                    eps_halfwidth=half, mu_halfwidth=half_mu,
                    n_eps=cfg.relocate_n_eps, n_mu=cfg.relocate_n_mu,
                    ess_floor=cfg.relocate_ess_floor,
                    mu_mode=cfg.scan_mu_mode,
                    dilute_window=cfg.dilute_window,
                    dense_window=cfg.dense_window,
                    verbose=verbose)
                eps_ns_new, mu_new, js = sc["eps_nd"], sc["mu"], sc["js"]
                curvature = float(sc["curvature"])
                stalled = False
                rescued = False
                at_bound = bool(sc["at_edge"])
                # A scan always "succeeds"; what says whether it found a real
                # minimum is the curvature (nan == no interior parabola) and
                # at_bound.
                opt_success = bool(np.isfinite(curvature) and not at_bound)
                if verbose:
                    print(f"[relocate] window +-{half:.4f} in eps_nd, "
                          f"+-{half_mu:.4f} in mu;  moved "
                          f"{eps_ns_new - eps_ns:+.6f}", flush=True)

                if cfg.store_diagnostics:
                    sp = profile_s(
                        rho_r, u_r, centers_ref, P_ref,
                        s_grid=np.linspace(cfg.s_profile_lo, cfg.s_profile_hi,
                                           cfg.s_profile_n),
                        sigma_x=cfg.sigma_x, r_penalty=cfg.r_penalty,
                        w_asym=cfg.w_asym)
                    j_fit = int(np.argmin(np.abs(sp["s_grid"] - s_use)))
                    j_min = int(np.argmin(sp["obj"]))
                    diag_arrays.update({
                        "scan_eps": sc["eps_grid"], "scan_js": sc["prof"],
                        "scan_mu": sc["mu_at"], "scan_ess": sc["ess"],
                        "scan_halfwidth": np.array([half]),
                        "scan_admissible": sc["admissible"],
                        "scan_frac_admissible":
                            np.array([sc["frac_admissible"]]),
                        "scan_eps_anchor": np.array([eps_ns]),
                        "s_grid": sp["s_grid"], "s_obj": sp["obj"],
                        "s_match": sp["match"], "s_asym": sp["asym"],
                        "s_fitted": np.array([s_use]),
                        "s_argmin": np.array([sp["s_grid"][j_min]]),
                        "P_at_s_fitted": sp["P"][j_fit],
                        "P_at_s_argmin": sp["P"][j_min],
                        "P_at_s_zero": sp["P"][
                            int(np.argmin(np.abs(sp["s_grid"])))],
                        "reloc_rho": np.asarray(rho_r, np.float32),
                        "reloc_u": np.asarray(u_r, np.float32),
                        # Everything needed to rebuild, exactly, the histogram
                        # the JS objective compares against P*(x): the counts
                        # that carry the reweighting, and both theta vectors.
                        "reloc_C_ns": np.asarray(C_r, np.float32),
                        "reloc_C_sp": np.asarray(Ca_r, np.float32),
                        "reloc_N_mu": np.asarray(N_r, np.float32),
                        "theta_ref": np.asarray(theta_ref, float),
                        "theta_star": np.asarray(
                            [eps_ns_new, eps_sp, mu_new, 1.0, Mc, s_use],
                            float),
                    })
                    if verbose:
                        print(f"[s-profile] fitted s={s_use:+.5f} "
                              f"(obj {sp['obj'][j_fit]:.5g})   "
                              f"grid argmin s={sp['s_grid'][j_min]:+.5f} "
                              f"(obj {sp['obj'][j_min]:.5g})", flush=True)
            else:
                half = cfg.opt_halfwidth_per_step * abs(cfg.eps_sp_step)
                half_mu = half
                res = optimize_eps_mu_Mc_fixed_epsA_fixed_s(
                    theta_ref, eps_sp, rho_r, u_r, C_r, Ca_r, N_r,
                    edges_ref, P_ref, L_fixed=None,
                    eps_halfwidth=half, mu_halfwidth=half_mu)
                eps_ns_new, _, mu_new, _, _, _ = res.theta_star
                js = float(res.fun)
                opt_success = bool(res.success)

                stalled = bool(abs(float(eps_ns_new) - eps_ns) < cfg.stall_tol)
                at_bound = bool(
                    abs(abs(float(eps_ns_new) - eps_ns) - half) < 1e-9)
                rescued = False

                if stalled and cfg.scan_fallback:
                    sc = scan_eps_mu_fixed_epsA_fixed_s(
                        theta_ref, eps_sp, rho_r, u_r, C_r, Ca_r, N_r,
                        edges_ref, P_ref, eps_halfwidth=half,
                        mu_halfwidth=half_mu, verbose=verbose)
                    if sc["js"] <= js:
                        eps_ns_new, mu_new, js = (sc["eps_nd"], sc["mu"],
                                                  sc["js"])
                        curvature = float(sc["curvature"])
                        rescued = True

            d_eps = float(eps_ns_new) - eps_ns
            eps_clamped = bool(abs(d_eps) > cfg.max_abs_eps_step)
            if eps_clamped:
                # This must be flagged, not just warned about: a clamped step
                # reports eps_nd = anchor +- max_abs_eps_step EXACTLY, which
                # looks like a located value and is not one.
                print(f"[warn] |d eps_nd| = {abs(d_eps):.4f} exceeds "
                      f"max_abs_eps_step={cfg.max_abs_eps_step}; CLAMPING -- "
                      f"the reported eps_nd is the clamp, not a minimum",
                      flush=True)
                eps_ns_new = eps_ns + math.copysign(cfg.max_abs_eps_step, d_eps)

            eps_ns = float(eps_ns_new)
            mu = float(mu_new)

            rec = dict(
                index=i,
                mode=("relocate" if relocating else "continuation"),
                d_eps_d=float(d_eps_d),
                curvature=float(curvature),
                eps_d=float(eps_sp),
                eps_d_prev=float(eps_sp_prev),
                eps_nd=float(eps_ns),
                mu=float(mu),
                mu_star_ref=float(mu_star),
                s=float(s_use),
                s_fit=float(s_fit),
                s_on_bound=bool(s_on_bound),
                s_rescued=bool(s_rescued),
                s_obj_lbfgs=float(s_obj_lbfgs),
                s_obj_grid=float(s_obj_grid),
                eps_clamped=bool(eps_clamped),
                s_flat=bool(s_flat),
                s_unidentified=bool(s_unidentified),
                s_span=float(s_span),
                s_lo=float(s_lo),
                s_hi=float(s_hi),
                s_singularity=float(s_sing),
                s_sigma_min_ratio=float(s_sigmin),
                s_fixed=bool(cfg.s0 is not None),
                r=float(r_fit),
                lam=float(lambdap),
                Mc=float(Mc),
                js=float(js),
                ess_mu=float(ess_mu),
                ess_frac=float(ess_mu / max(len(rho), 1)),
                mu_equal_area=float(guard["mu"]),
                mu_scout_ok=bool(guard["success"]),
                n_scout_sims=int(guard.get("n_sim", 0)),
                mean_rho=float(np.mean(rho)),
                min_crossings=int(diag["min_crossings"]),
                total_crossings=int(diag["total_crossings"]),
                mean_accept=float(diag["mean_accept"]),
                rho_spread=float(diag["rho_spread"]),
                opt_success=bool(opt_success),
                stalled=stalled,
                at_bound=at_bound,
                rescued_by_scan=rescued,
                fit_success=bool(fit["success"]),
                match_L2=float(fit["match_L2"]),
                asym_L2=float(fit["asym_L2"]),
                steps_per_replica=int(P_prod["steps"]),
                wall_seconds=float(time.perf_counter() - t_step),
            )
            points.append(rec)
            if cfg.archive_raw:
                last_raw = diag.get("raw", {})

            if verbose:
                flags = []
                if stalled:
                    flags.append("STALLED" + ("->rescued" if rescued else ""))
                if at_bound:
                    flags.append("AT-BOUND")
                if rec["min_crossings"] < cfg.min_crossings_warn:
                    flags.append("NO-TUNNELLING")
                if rec["ess_frac"] < 0.10:
                    flags.append("LOW-ESS")
                if relocating:
                    flags.append("RELOCATE")
                if s_rescued:
                    flags.append("S-RESCUED" + ("(bound)" if s_on_bound
                                                else ""))
                if s_unidentified:
                    flags.append("S-NOT-IDENTIFIABLE")
                if eps_clamped:
                    flags.append("EPS-CLAMPED")
                tag = ("  [" + " ".join(flags) + "]") if flags else ""
                print(f"[step {i + 1}/{grid.size}] eps_d={eps_sp:.4f}  "
                      f"eps_nd={eps_ns:.6f}  mu={mu:.6f}  s={s_use:.4f}  "
                      f"JS={js:.5f}  ESS/n={rec['ess_frac']:.2f}  "
                      f"cross(min)={rec['min_crossings']}  "
                      f"<rho>={rec['mean_rho']:.3f}  "
                      f"{rec['wall_seconds']:.0f}s{tag}", flush=True)

            eps_sp_prev = eps_sp

            if cfg.checkpoint:
                tmp = cfg.checkpoint + ".tmp"
                with open(tmp, "w") as fh:
                    json.dump(dict(points=points, eps_ns=eps_ns, mu=mu,
                                   eps_sp_prev=eps_sp_prev, s_ref=s_ref,
                                   next_index=i + 1, L=cfg.L,
                                   system=cfg.system, seed=cfg.seed,
                                   code_version=MC_LINE_VERSION,
                                   fingerprint=_ckpt_fingerprint(cfg)), fh)
                os.replace(tmp, cfg.checkpoint)
    finally:
        pool.close()
        pool.join()

    return dict(
        system=cfg.system, L=cfg.L, seed=cfg.seed,
        eps_sp_start=cfg.eps_sp_start, eps_sp_end=cfg.eps_sp_end,
        eps_sp_step=cfg.eps_sp_step,
        eps_nd_anchor=(cfg.eps_ns0 if cfg.eps_ns0 is not None else eps_ns0),
        mu_anchor=(cfg.mu0 if cfg.mu0 is not None else mu0),
        points=points,
        complete=bool(len(points) >= grid.size),
        steps_per_replica=steps_prod,
        sweeps_per_replica=steps_prod / float(cfg.L ** 2),
        n_replicas=cfg.n_replicas,
        centers_ref=centers_ref, edges_ref=edges_ref, P_ref=P_ref,
        raw=last_raw,
        diag_arrays=diag_arrays,
    )
