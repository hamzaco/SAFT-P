def lattice_gas_anchor(system):
    """Exact critical point at eps_d = 0.

    At eps_d = 0 every particle-particle contact carries -eps_nd regardless of
    patch identity, so the model reduces to the plain 2D lattice gas:

        eps_nd,c = 2 ln(1 + sqrt 2) = 1.762747      mu_c = 2 eps_nd,c + ln g

    with g the number of distinguishable orientations (2 stick, 4 L).  This is
    where the notebook's first cell starts.  Note the notebook used ln 4 for
    both geometries; ln g is the correct generalisation and matters only for
    the stick system.
    """
    g = SYSTEMS[system]["n_orient"]
    eps_nd = 2.0 * math.log(1.0 + math.sqrt(2.0))
    return float(eps_nd), float(2.0 * eps_nd + math.log(g))


