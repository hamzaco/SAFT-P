@nb.njit(cache=True)
def numba_seed(s):
    """Seed numba's internal np.random state.

    np.random.seed() called from *python* does not touch the state used inside
    njit code, and that state is inherited across fork().  Every worker process
    must call this with a distinct value or the replicas are not independent.
    """
    np.random.seed(s)
    return np.random.randint(0, 1 << 30)


# ----------------------------------------------------------------------------
# 2D Ising reference distribution P*(x)  (numba Wolff, cached)
# ----------------------------------------------------------------------------
@nb.njit(cache=True)
def _wolff_magnetisations(L, p_add, burnin, nsamples, seed):
    np.random.seed(seed)
    N = L * L
    spins = np.empty((L, L), dtype=np.int8)
    for i in range(L):
        for j in range(L):
            spins[i, j] = 1 if np.random.random() < 0.5 else -1

    stack_i = np.empty(N, dtype=np.int32)
    stack_j = np.empty(N, dtype=np.int32)
    in_cluster = np.zeros((L, L), dtype=np.bool_)
    touched_i = np.empty(N, dtype=np.int32)
    touched_j = np.empty(N, dtype=np.int32)

    out = np.empty(nsamples, dtype=np.float64)

    for it in range(burnin + nsamples):
        x = np.random.randint(0, L)
        y = np.random.randint(0, L)
        target = spins[x, y]

        ntouch = 0
        sp = 0
        stack_i[sp] = x
        stack_j[sp] = y
        sp += 1
        in_cluster[x, y] = True
        touched_i[ntouch] = x
        touched_j[ntouch] = y
        ntouch += 1

        while sp > 0:
            sp -= 1
            i = stack_i[sp]
            j = stack_j[sp]
            for d in range(4):
                if d == 0:
                    ni = i
                    nj = (j + 1) % L
                elif d == 1:
                    ni = i
                    nj = (j - 1) % L
                elif d == 2:
                    ni = (i + 1) % L
                    nj = j
                else:
                    ni = (i - 1) % L
                    nj = j
                if (not in_cluster[ni, nj]) and spins[ni, nj] == target:
                    if np.random.random() < p_add:
                        in_cluster[ni, nj] = True
                        stack_i[sp] = ni
                        stack_j[sp] = nj
                        sp += 1
                        touched_i[ntouch] = ni
                        touched_j[ntouch] = nj
                        ntouch += 1

        for t in range(ntouch):
            spins[touched_i[t], touched_j[t]] *= -1
            in_cluster[touched_i[t], touched_j[t]] = False

        if it >= burnin:
            m = 0
            for i in range(L):
                for j in range(L):
                    m += spins[i, j]
            out[it - burnin] = m / N

    return out


def smooth_histogram_gaussian(x_centers, p_hist, sigma=1.0):
    """Verbatim from the manuscript notebooks."""
    x_centers = np.asarray(x_centers, float)
    p_hist = np.asarray(p_hist, float)
    dx = float(np.mean(np.diff(x_centers)))
    if not np.allclose(np.diff(x_centers), dx, rtol=1e-4, atol=1e-8):
        raise ValueError("x_centers must be uniformly spaced.")
    sigma_bins = sigma / dx
    halfw = int(np.ceil(4 * sigma_bins))
    kx = np.arange(-halfw, halfw + 1, dtype=float)
    K = np.exp(-0.5 * (kx / sigma_bins) ** 2)
    K /= K.sum()
    p_pad = np.pad(p_hist, (halfw, halfw), mode="reflect")
    p_conv = np.convolve(p_pad, K, mode="same")[halfw:-halfw]
    p_conv /= _trapz(p_conv, x_centers)
    return x_centers, p_conv


def ising_reference(cache_path=None, L_ising=64, burnin=3000,
                    nsamples=20000, seed=20260814, nbins=101, n_pad=6,
                    smooth_sigma=0.05, verbose=True):
    """Universal 2D-Ising order-parameter distribution P*(x), unit variance.

    Same construction as the notebooks (L=64 Wolff at Tc, 3000 burn-in
    clusters, 20000 samples, 101 bins + 6 zero-padding bins per side, Gaussian
    smoothing sigma=0.05), but with a fixed seed and an on-disk cache, so that
    every task in the campaign fits against a bit-identical reference.

    The cache is shared with mc_fss_core.ising_reference -- same defaults, same
    seed, same file layout -- so the two campaigns are directly comparable.
    """
    if cache_path is not None and os.path.exists(cache_path):
        z = np.load(cache_path)
        return z["centers"], z["edges"], z["P_smooth"]

    Tc = 2.0 / math.log(1.0 + math.sqrt(2.0))
    p_add = 1.0 - math.exp(-2.0 / Tc)
    if verbose:
        print(f"[ising-ref] Wolff L={L_ising} Tc={Tc:.6f} "
              f"burnin={burnin} samples={nsamples} seed={seed}", flush=True)

    m = _wolff_magnetisations(int(L_ising), float(p_add), int(burnin),
                              int(nsamples), int(seed))

    m_mean = float(m.mean())
    m_std = float(m.std(ddof=1))
    x_samples = (m - m_mean) / m_std

    R_data = float(np.max(np.abs(x_samples)))
    dx = 2.0 * R_data / nbins
    R = R_data + n_pad * dx
    edges = np.linspace(-R, R, (nbins + 2 * n_pad) + 1)
    hist, _ = np.histogram(x_samples, bins=edges, density=True)
    centers = 0.5 * (edges[:-1] + edges[1:])

    centers, P_smooth = smooth_histogram_gaussian(centers, hist,
                                                  sigma=smooth_sigma)
    P_smooth = P_smooth / _trapz(P_smooth, centers)

    if cache_path is not None:
        os.makedirs(os.path.dirname(os.path.abspath(cache_path)), exist_ok=True)
        np.savez_compressed(cache_path, centers=centers, edges=edges,
                            P_smooth=P_smooth, L_ising=L_ising, seed=seed,
                            nsamples=nsamples, burnin=burnin)
        if verbose:
            print(f"[ising-ref] cached -> {cache_path}", flush=True)

    return centers, edges, P_smooth


