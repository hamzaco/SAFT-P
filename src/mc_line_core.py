"""
mc_line_core.py -- finite-size critical *line* for stick / L-shaped patchy
particles on the square lattice.

Purpose
-------
Run the continuation sweep of notebooks/mc_sims_{l,stick}_shaped.ipynb --
i.e. `main(eps_ns, eps_sp_prev, mu)`, which traces the critical line
eps_nd,c(eps_d) by stepping eps_d and re-locating criticality at every step --
at several lattice sizes (L = 10, 20, 30), so that the whole line can be
extrapolated to the thermodynamic limit rather than a single state point.

Relation to the rest of src/
----------------------------
  mc_fss_core.py   one point, eps_d FIXED, anchored on the logged L=10 trace.
                   Answers "how far does eps_nd,c move with L at eps_d=1.96?"
  mc_line_core.py  (this file) the notebook's DIFFERENTIAL continuation, run
                   at several L.  Answers "how far does the whole line move?"

The estimator is the notebook's, function for function:

    equal-area mu search by simulation
      -> mu* refined by histogram reweighting in mu
      -> mixed-field (s, r) fit of  M = rho - s*u  against the 2D-Ising
         universal order-parameter distribution P*(x)
      -> joint (eps_nd, mu) reweighting from eps_d_prev to eps_d, minimising
         the Jensen-Shannon divergence to P*(x)

Those functions are carried over verbatim (they are byte-identical to the ones
in mc_fss_core.py, which were themselves lifted from the notebook).  This file
is deliberately self-contained: it imports only simulate_functions_min, so the
line campaign cannot be broken by an edit to the fixed-eps_d campaign.

What changed relative to the notebook cell
------------------------------------------
 1. L is a parameter.  Chain length, snapshot interval and acceptance-block
    size all scale with it:

        steps(L) = sweeps_ref * (L/L_ref)^z * L^2 ,   z = 2.17

    z is the dynamic exponent for local single-site dynamics in the 2D Ising
    universality class; sweeps_ref = 6e6 at L_ref = 10 reproduces the
    notebook's 600_000_000 attempts.  L=10/20/30 -> 6.0e8 / 1.08e10 / 5.9e10.

 2. MC replicas run in parallel worker processes.  The notebook ran its 5
    replicas sequentially inside build_data_mu_cpu.

 3. The numba RNG is seeded per worker.  numba's np.random state is
    process-global and is INHERITED ACROSS fork(); np.random.seed() from
    python does not touch it.  Without an explicit @njit reseed every replica
    in a forked pool reproduces the identical Markov chain, and the error bars
    look perfectly healthy while carrying no information.

 4. block_size scales with the chain.  simulate_lattice_numba allocates
    simulation_steps//block_size float64s for the acceptance trace; at the
    notebook's block_size=1000 and L=30's 5.9e10 steps that is ~470 MB per
    replica.

 5. The equal-area mu scout runs on SHORT chains (scout_frac of full length)
    and the production chain is then run once at the located mu.  The notebook
    used full-length chains inside find_mu_equal_areas_by_simulation and reused
    the last one as the production data; at L=30 that multiplies the cost of
    every continuation step by the scout's iteration count.  Set
    --scout-frac 1.0 to recover the notebook's behaviour exactly.

 6. The sweep is cut into segments so it can be spread over a SLURM array, and
    each segment checkpoints after every eps_d step so it can be chained across
    walltime limits.

 7. The 2D-Ising reference P*(x) is generated by a numba Wolff sampler and
    cached to disk, so every task in the campaign fits against a bit-identical
    reference instead of redrawing it (and adding noise) per call.

 8. Every raw sample (rho, u, C_ns, C_sp, N_mu) at the final pass of each step
    is optionally archived, so the mixed-field analysis can be redone offline.

 9. L-BFGS-B stalls are detected and flagged.  The notebook's
    optimize_eps_mu_Mc_fixed_epsA_fixed_s minimises over a digitised histogram,
    so the objective is piecewise constant and the finite-difference gradient
    is noise.  In continuation mode this is usually harmless -- each step
    starts displaced by d(eps_d) on the steep flank -- but not always: the
    logged bent-geometry trace has runs of 3-4 consecutive steps with eps_nd
    frozen to 5 decimals.  Every step now records `stalled`, and
    --scan-fallback re-does the stalled ones with a grid scan of the same
    objective.

Sign conventions are inherited unchanged from the notebook and are internally
consistent with the MC kernel in simulate_functions_min.py (which minimises
Phi = E_bonds + sum_k mu[s_k], i.e. `mu` enters as an occupancy penalty).  They
are deliberately NOT "corrected" here: the published L=10 line comes out of
this exact code path and the finite-size displacement is a difference taken at
fixed convention.

Naming: the notebook calls the two couplings (eps_ns, eps_sp); the manuscript
calls them (eps_nd, eps_d).  They are the same two numbers.  This file uses the
notebook names internally and the manuscript names in output columns.
"""

