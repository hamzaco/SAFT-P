# lattice construction
# ----------------------------------------------------------------------------
def make_lattices(species, L, mode, rng):
    """Initial configurations.

    'middle' reproduces the notebook exactly: every replica starts from the
    same random mixture with weights [1,...,1,4] over (orientations, vacancy).
    'mixed' additionally supplies a dilute and a dense start, so that agreement
    between replicas started from opposite basins is itself an equilibration
    test -- which matters at L=30, where a single chain may not tunnel.
    """
    n = len(species)
    N_total = L * L
    ids = np.arange(n, dtype=np.int64)

    def from_weights(wts):
        wts = np.asarray(wts, float)
        wts = wts / wts.sum()
        counts = [int(w * N_total) for w in wts]
        counts[0] += N_total - sum(counts)
        flat = np.concatenate([np.full(c, ids[i], dtype=np.int64)
                               for i, c in enumerate(counts)])
        rng.shuffle(flat)
        return flat.reshape((L, L))

    w_middle = np.array(list(np.ones(n - 1)) + [4.0])
    lat_middle = from_weights(w_middle)
    if mode == "middle":
        return [lat_middle]

    w_dilute = np.array(list(np.ones(n - 1) * 0.1) + [float(n - 1) * 0.9 / 0.1])
    w_dense = np.array(list(np.ones(n - 1)) + [0.15 * (n - 1)])
    lat_dilute = from_weights(w_dilute)
    lat_dense = from_weights(w_dense)
    return [lat_dense, lat_dilute, lat_middle]


