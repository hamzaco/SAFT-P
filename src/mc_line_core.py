def run_ref_once_mu(lattice0, species, species_mu_indices,
                    eps_ns0, eps_sp0, mu0, *,
                    steps, snapshot_interval, buffer_size, block_size,
                    empty_index=-1, beta=1.0, keep_final=False):
    """One MC replica at (eps_ns0, eps_sp0, mu0).  Same J_patch as the notebooks."""
    lattice_int = to_int_lattice(lattice0)

    def J_patch(epsp, epsn):
        return np.array([[-epsn, -epsn, 0.0],
                         [-epsn, -epsn - epsp, 0.0],
                         [0.0, 0.0, 0.0]], float)

    Jref = J_patch(float(eps_sp0), float(eps_ns0))
    patches_by_species = np.asarray([getattr(s, "patches") for s in species],
                                    dtype=np.uint8)

    n_species = len(species)
    if empty_index < 0:
        empty_index = n_species - 1
    empty_index = int(empty_index)

    mu_table = np.zeros(n_species, dtype=np.float64)
    idx = np.unique(np.asarray(species_mu_indices, dtype=np.int64))
    idx = idx[(idx >= 0) & (idx < n_species)]
    mu_table[idx] = float(mu0)

    snap_counts, energies, densities, lat_final = simulate_lattice_numba(
        lattice_int,
        Jref,
        patches_by_species,
        mu_table,
        empty_index=empty_index,
        eps_ns0=float(eps_ns0),
        eps_sp0=float(eps_sp0),
        simulation_steps=int(steps),
        beta=float(beta),
        snapshot_interval=int(snapshot_interval),
        buffer_size=int(buffer_size),
        block_size=int(block_size),
        species_mu_indices=idx,
    )

    snap_counts = dict(snap_counts)
    N_sites = int(snap_counts["N_sites"])
    if "rho_mu" not in snap_counts or "N_mu" not in snap_counts:
        dens = np.asarray(densities, float)
        rho_mu = dens[:, idx].sum(axis=1) if idx.size else np.zeros(dens.shape[0])
        snap_counts["rho_mu"] = rho_mu
        snap_counts["N_mu"] = rho_mu * float(N_sites)

    for k in ["N_mu", "rho_mu", "Nocc_total", "rho_total", "u", "C_ns", "C_sp"]:
        if k in snap_counts:
            snap_counts[k] = np.asarray(snap_counts[k], float).ravel()

    if keep_final:
        snap_counts["lat_final"] = np.asarray(lat_final, dtype=np.int8)
    return snap_counts


# --- worker plumbing --------------------------------------------------------
_W = {}


def _worker_init(payload, base_seed):
    """Fork/spawn initialiser: pin threads, seed numba, cache static arrays."""
    for v in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS",
              "NUMEXPR_NUM_THREADS", "NUMBA_NUM_THREADS"):
        os.environ[v] = "1"
    pid_tag = os.getpid() & 0xFFFF
    seed = (int(base_seed) * 1_000_003 + pid_tag) % (2 ** 31 - 1)
    numba_seed(seed)
    np.random.seed(seed)
    _W.update(payload)
    _W["seed"] = seed


def _worker_run(args):
    (rep, call, lat, eps_ns, eps_sp, mu, steps, snap, buf, block) = args
    # Distinct stream per (replica, simulate() call).  Without the `call` term
    # every simulate() call inside one continuation step would restart the same
    # chain from the same state, and the scout would keep re-measuring it.
    numba_seed((_W["seed"] + 7919 * (rep + 1) + 104729 * (call + 1))
               % (2 ** 31 - 1))
    out = run_ref_once_mu(
        lat, _W["species"], _W["species_mu_indices"],
        eps_ns, eps_sp, mu,
        steps=steps, snapshot_interval=snap, buffer_size=buf,
        block_size=block, empty_index=_W["empty_index"], beta=_W["beta"],
    )
    keep = ["N_mu", "rho_mu", "Nocc_total", "rho_total", "u", "C_ns", "C_sp"]
    slim = {k: out[k] for k in keep}
    slim["N_sites"] = out["N_sites"]
    slim["accept_rate"] = out["accept_rate"]
    slim["rep"] = rep
    return slim


def _tunnelling_stats(rho, lo=0.4, hi=0.6):
    """Number of dilute<->dense round trips in a raw (unshuffled) trace.

    `crossings == 0` for any replica means that point is not ergodic on the
    chain length used, and the located critical point should not be trusted.
    """
    rho = np.asarray(rho, float)
    state = np.zeros(rho.size, dtype=np.int8)
    state[rho <= lo] = -1
    state[rho >= hi] = +1
    nz = state[state != 0]
    if nz.size == 0:
        return dict(crossings=0, frac_dilute=0.0, frac_dense=0.0,
                    frac_middle=1.0)
    crossings = int(np.sum(nz[1:] != nz[:-1]))
    return dict(
        crossings=crossings,
        frac_dilute=float(np.mean(rho <= lo)),
        frac_dense=float(np.mean(rho >= hi)),
        frac_middle=float(np.mean((rho > lo) & (rho < hi))),
    )


def build_data_mu(pool, lattices, species, species_mu_indices,
                  eps_ns, eps_sp, mu, beta,
                  steps, snapshot_interval, buffer_size, block_size,
                  n_replicas, burn_frac, rng_shuffle, L, call_id=0,
                  keep_raw=False):
    """Parallel replacement for the notebook's build_data_mu_cpu."""
    jobs = []
    for r in range(int(n_replicas)):
        lat = lattices[r % len(lattices)].copy()
        jobs.append((r, int(call_id), lat, float(eps_ns), float(eps_sp),
                     float(mu), int(steps), int(snapshot_interval),
                     int(buffer_size), int(block_size)))

    runs = list(pool.map(_worker_run, jobs)) if pool is not None \
        else [_worker_run(j) for j in jobs]
    runs.sort(key=lambda d: d["rep"])

    keys = ["N_mu", "rho_mu", "Nocc_total", "rho_total", "u", "C_ns", "C_sp"]

    per_rep = []
    trimmed = []
    for r in runs:
        n = r["rho_mu"].size
        b = int(np.floor(burn_frac * n))
        st = _tunnelling_stats(r["rho_mu"][b:])
        st["rep"] = r["rep"]
        st["accept_rate"] = r["accept_rate"]
        st["mean_rho"] = float(np.mean(r["rho_mu"][b:]))
        st["n_samples"] = int(n - b)
        per_rep.append(st)
        trimmed.append({k: r[k][b:] for k in keys})

    cat = {k: np.concatenate([t[k] for t in trimmed]) for k in keys}
    raw = {k: cat[k].copy() for k in keys} if keep_raw else {}

    idx = rng_shuffle.permutation(len(cat["Nocc_total"]))
    for k in keys:
        cat[k] = cat[k][idx]

    N_sites = int(runs[0]["N_sites"])

    diag = dict(
        per_replica=per_rep,
        total_crossings=int(sum(p["crossings"] for p in per_rep)),
        min_crossings=int(min(p["crossings"] for p in per_rep)),
        mean_accept=float(np.mean([p["accept_rate"] for p in per_rep])),
        rho_spread=float(np.max([p["mean_rho"] for p in per_rep])
                         - np.min([p["mean_rho"] for p in per_rep])),
        raw=raw,
    )

    return ReweightDataMU(
        beta=beta, L=L, N_sites=N_sites,
        eps_ns0=eps_ns, eps_sp0=eps_sp, mu0=mu,
        N_mu=cat["N_mu"], rho_mu=cat["rho_mu"], rho_total=cat["rho_total"],
        u=cat["u"], C_ns=cat["C_ns"], C_sp=cat["C_sp"], diag=diag,
    )


