def to_int_lattice(lat):
    lat = np.asarray(lat)
    if np.issubdtype(lat.dtype, np.integer):
        return lat.astype(np.int64, copy=False)
    return np.vectorize(lambda p: p.index, otypes=[np.int64])(lat)


