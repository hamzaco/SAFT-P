def _ess(w):
    w = np.asarray(w, float)
    s1 = w.sum()
    s2 = (w * w).sum()
    return (s1 * s1) / max(s2, 1e-300)


def _weights_mu(N_counts, mu_new, mu_ref, beta=1.0, clip=700.0):
    dmu = float(mu_new - mu_ref)
    logw = -beta * dmu * np.asarray(N_counts, float)
    logw -= np.max(logw)
    logw = np.clip(logw, -clip, None)
    return np.exp(logw)


def _rho_hist_density(rho, w, edges):
    counts, _ = np.histogram(rho, bins=edges, weights=w, density=False)
    W = counts.sum()
    p = counts / max(W, 1e-300)
    width = np.diff(edges)
    dens = p / width
    centers = 0.5 * (edges[:-1] + edges[1:])
    return centers, dens


def _area_in_window(edges, dens, lo, hi):
    lo = float(lo)
    hi = float(hi)
    Le = edges[:-1]
    Re = edges[1:]
    overlap = np.maximum(0.0, np.minimum(Re, hi) - np.maximum(Le, lo))
    return float(np.sum(dens * overlap))


def equal_peak_mu_in_rho_by_reweighting(
    rho, N_counts, mu_ref, *,
    beta=1.0,
    rho_edges=None, rho_bins=200,
    dilute_window=(0.0, 0.3),
    dense_window=(0.7, 1.0),
    ess_min=2_000,
    mu0=None, step0=0.01, max_bracket=20, tol=5e-3, max_bisect=30,
    verbose=True,
):
    """Verbatim from the notebooks."""
    rho = np.asarray(rho, float)
    N = np.asarray(N_counts, float)

    if rho_edges is None:
        lo, hi = float(np.min(rho)), float(np.max(rho))
        edges = np.linspace(lo, hi, int(rho_bins) + 1)
    else:
        edges = np.asarray(rho_edges, float)

    def f_of_mu(mu_trial):
        w = _weights_mu(N, mu_trial, mu_ref, beta=beta)
        ess = _ess(w)
        _, dens = _rho_hist_density(rho, w, edges)
        Ad = _area_in_window(edges, dens, *dilute_window)
        Ah = _area_in_window(edges, dens, *dense_window)
        return (Ah - Ad), ess, w, dens

    mu_start = float(mu_ref if mu0 is None else mu0)
    f0, ess0, w0, dens0 = f_of_mu(mu_start)
    if verbose:
        print(f"[equal-rho] mu0={mu_start:.6f}, dA={f0:+.4f}, ESS~{ess0:.0f}",
              flush=True)

    if abs(f0) < tol and ess0 >= ess_min:
        centers, _ = _rho_hist_density(rho, w0, edges)
        return dict(mu_star=mu_start, success=True, ess=float(ess0),
                    centers=centers, density_star=dens0, w_star=w0)

    direction = 1.0 if f0 > 0 else -1.0
    step = float(step0)

    for k in range(max_bracket):
        mu_try = mu_start + direction * step * (k + 1)
        ft, esst, wt, denst = f_of_mu(mu_try)
        if verbose:
            print(f"[equal-rho] bracket mu={mu_try:.6f}, dA={ft:+.4f}, "
                  f"ESS~{esst:.0f}", flush=True)
        if np.sign(ft) != np.sign(f0):
            if f0 > 0:
                mu_lo, f_lo, w_lo, dens_lo = mu_try, ft, wt, denst
                mu_hi, f_hi, w_hi, dens_hi = mu_start, f0, w0, dens0
            else:
                mu_lo, f_lo, w_lo, dens_lo = mu_start, f0, w0, dens0
                mu_hi, f_hi, w_hi, dens_hi = mu_try, ft, wt, denst
            break
    else:
        centers, _ = _rho_hist_density(rho, w0, edges)
        return dict(mu_star=mu_start, success=False, ess=float(ess0),
                    centers=centers, density_star=dens0, w_star=w0,
                    reason="failed to bracket")

    for it in range(max_bisect):
        mu_mid = 0.5 * (mu_lo + mu_hi)
        fm, essm, wm, densm = f_of_mu(mu_mid)
        if verbose:
            print(f"[equal-rho] bisect mu={mu_mid:.6f}, dA={fm:+.4f}, "
                  f"ESS~{essm:.0f}", flush=True)
        if abs(fm) < tol and essm >= ess_min:
            centers, _ = _rho_hist_density(rho, wm, edges)
            return dict(mu_star=mu_mid, success=True, ess=float(essm),
                        centers=centers, density_star=densm, w_star=wm)
        if np.sign(fm) == np.sign(f_lo):
            mu_lo, f_lo, w_lo, dens_lo = mu_mid, fm, wm, densm
        else:
            mu_hi, f_hi, w_hi, dens_hi = mu_mid, fm, wm, densm

    centers, _ = _rho_hist_density(rho, wm, edges)
    return dict(mu_star=mu_mid, success=False, ess=float(essm),
                centers=centers, density_star=densm, w_star=wm,
                reason="max bisection iterations")


def resample_at_mu_star(data: ReweightDataMU, mu_star: float, rng=None):
    """Verbatim from the notebooks (systematic / stratified resampling)."""
    if rng is None:
        rng = np.random.default_rng(1234)
    dG = -data.beta * (mu_star - data.mu0) * np.asarray(data.N_mu, float)
    dG -= dG.max()
    w = np.exp(dG)
    w /= max(w.sum(), 1e-300)
    c = np.cumsum(w)
    u0 = rng.random() / len(w)
    u = u0 + np.arange(len(w)) / len(w)
    idx = np.searchsorted(c, u, side="right")
    idx = np.clip(idx, 0, len(w) - 1)
    return dict(
        indices=idx,
        weights=w,
        rho_mu=data.rho_mu[idx].copy(),
        rho_total=data.rho_total[idx].copy(),
        N_mu=data.N_mu[idx].copy(),
        u=data.u[idx].copy(),
        C_ns=data.C_ns[idx].copy(),
        C_sp=data.C_sp[idx].copy(),
    )


# --- mixed-field fit (s, r) + KDE -------------------------------------------
def _wmean(x, w):
    return float(np.sum(w * x) / max(np.sum(w), 1e-300))


def _wstd(x, w):
    m = _wmean(x, w)
    v = _wmean((x - m) ** 2, w)
    return float(np.sqrt(max(v, 1e-300)))


def _kde_fixed_sigma_on_grid(x_samples, x_grid, sigma_x, w):
    x_samples = np.asarray(x_samples, float)
    x_grid = np.asarray(x_grid, float)
    w = np.asarray(w, float).ravel()
    w = np.where(np.isfinite(w) & (w > 0), w, 0.0)
    w /= max(w.sum(), 1e-300)

    u = (x_grid[:, None] - x_samples[None, :]) / sigma_x
    K = np.exp(-0.5 * u * u)
    P = (K @ w) / (sigma_x * np.sqrt(2 * np.pi))
    P /= max(_trapz(P, x_grid), 1e-300)
    return P


def fit_s_r_from_reweighted(rho, u, x_ref, P_ref, s_ref, *,
                            weights=None, L=None, beta_over_nu=1 / 8,
                            sigma_x=0.05, r_penalty=5e-2,
                            bounds_s=(-5.0, 5.0), bounds_r=(-1.0, 1.0),
                            w_asym=0.5):
    """Verbatim from the notebooks.

    Note `s_ref is not None` pins s inside the objective, so the returned
    fit['s'] is then whatever x0/bounds allow -- exactly the notebook's
    behaviour, kept so the two pipelines agree step for step.
    """
    rho = np.asarray(rho, float).ravel()
    u = np.asarray(u, float).ravel()
    x_ref = np.asarray(x_ref, float).ravel()
    P_ref = np.asarray(P_ref, float).ravel()

    if weights is None:
        w = np.ones_like(rho, float)
    else:
        w = np.asarray(weights, float).ravel()
        w = np.where(np.isfinite(w) & (w > 0), w, 0.0)
    w /= max(w.sum(), 1e-300)

    def build_x_pdf(s, r):
        M = rho - s * u
        M_center = _wmean(M, w)
        M_std = max(_wstd(M, w), 1e-300)
        x_samples = (M - M_center) / M_std
        P_est = _kde_fixed_sigma_on_grid(x_samples, x_ref, sigma_x, w)
        return 1.0 / M_std, x_samples, P_est

    def objective(theta):
        s, r = float(theta[0]), float(theta[1])
        if s_ref is not None:
            s = s_ref
        _, _, P_est = build_x_pdf(s, r)

        diff = P_est - P_ref
        match_L2 = _trapz(diff * diff, x_ref)

        P_mir = np.interp(-x_ref, x_ref, P_est)
        A = 0.5 * (P_est - P_mir)
        asym_L2 = _trapz(A * A, x_ref)

        return match_L2 + w_asym * asym_L2 + r_penalty * (r * r)

    x0 = np.array([0.0, 0.0], float)
    bounds = [bounds_s, bounds_r]

    res = minimize(objective, x0, method="L-BFGS-B", bounds=bounds,
                   options=dict(maxiter=300, ftol=1e-9))
    if (not res.success) or ("ABNORMAL" in str(res.message)):
        res = minimize(objective, res.x, method="Nelder-Mead",
                       options=dict(maxiter=800, xatol=1e-6, fatol=1e-6))

    s_opt, r_opt = map(float, res.x)
    alpha_opt, xs_opt, P_fit = build_x_pdf(s_opt, r_opt)

    diff = P_fit - P_ref
    match_L2 = float(_trapz(diff * diff, x_ref))
    P_mir = np.interp(-x_ref, x_ref, P_fit)
    A = 0.5 * (P_fit - P_mir)
    asym_L2 = float(_trapz(A * A, x_ref))

    return dict(success=bool(res.success), message=str(res.message),
                s=s_opt, r=r_opt, alpha=alpha_opt,
                x=x_ref, P_fit=P_fit, P_ref=P_ref,
                match_L2=match_L2, asym_L2=asym_L2, fun=float(res.fun))


# --- theta reweight objective (eps, mu) at fixed eps_d and fixed s -----------
def _parse_theta_with_s(theta):
    t = list(map(float, theta))
    be, beA, bm, L, Mc = t[:5]
    s = t[5] if len(t) >= 6 else 0.0
    return be, beA, bm, L, Mc, s


def kl_q_p(q, p, eps=1e-12):
    q = np.asarray(q, float)
    p = np.asarray(p, float)
    q = q / max(q.sum(), 1e-300)
    p = p / max(p.sum(), 1e-300)
    q = np.clip(q, eps, 1.0)
    p = np.clip(p, eps, 1.0)
    q /= q.sum()
    p /= p.sum()
    return float(np.sum(q * (np.log(q) - np.log(p))))


def js_div(q, p, eps=1e-12):
    q = np.asarray(q, float)
    p = np.asarray(p, float)
    q = q / max(q.sum(), 1e-300)
    p = p / max(p.sum(), 1e-300)
    q = np.clip(q, eps, 1.0)
    p = np.clip(p, eps, 1.0)
    q /= q.sum()
    p /= p.sum()
    m = 0.5 * (q + p)
    return 0.5 * kl_q_p(q, m, eps) + 0.5 * kl_q_p(p, m, eps)


def reweight_from_samples_counts_with_s(M_ref, C, Ca, N, theta_prime,
                                        theta_ref, *, rho=None, u=None,
                                        clip=700.0, return_Mprime=False):
    """Verbatim from the notebooks."""
    be, beA, bm, _, _, s_ref = _parse_theta_with_s(theta_ref)
    bep, beAp, bmp, _, _, s_prime = _parse_theta_with_s(theta_prime)

    if (rho is not None) and (u is not None):
        Mprime = np.asarray(rho, float) - float(s_prime) * np.asarray(u, float)
    else:
        Mprime = np.asarray(M_ref, float)

    d_be, d_beA, d_bm = (bep - be), (beAp - beA), (bmp - bm)
    logw = (-(d_be) * np.asarray(C, float)
            - (d_beA) * np.asarray(Ca, float)
            - (d_bm) * np.asarray(N, float))

    logw = np.clip(logw - np.max(logw), -clip, None)
    w = np.exp(logw)

    return (w, Mprime) if return_Mprime else w


def weighted_hist_and_sigma(x, w, edges, epsilon=1e-12, *,
                            return_nonempty=True, empty_tol=0.0):
    x = np.asarray(x, float)
    w = np.asarray(w, float)
    n = x.size
    K = len(edges) - 1

    idx = np.clip(np.digitize(x, edges) - 1, 0, K - 1)

    S1 = np.bincount(idx, weights=w, minlength=K)
    S2 = np.bincount(idx, weights=w * w, minlength=K)
    W = float(w.sum())

    p = S1 / max(W, epsilon)
    num = S2 - (S1 ** 2) / max(n, 1)
    sigma2 = np.maximum(num / max(W, epsilon), 0.0)
    centers = 0.5 * (edges[1:] + edges[:-1])

    if return_nonempty:
        nonempty = p > float(empty_tol)
        return centers, p, sigma2, nonempty
    return centers, p, sigma2


def make_objective_fixed_epsA_fixed_s_with_sweights(theta_ref, epsA_fixed,
                                                    rho, u, C, Ca, N,
                                                    edges_ref, p_ref, *,
                                                    L_fixed=None,
                                                    epsilon=1e-12):
    """Verbatim from the notebooks.  Returns JS(reweighted || Ising) at (eps, mu).

    Note the objective is evaluated on a *digitised* histogram, so it is
    piecewise constant in its arguments.  See the module docstring, point 9.
    """
    be_ref, beA_ref, bm_ref, L_ref, Mc_ref, s_ref = _parse_theta_with_s(theta_ref)
    if L_fixed is None:
        L_fixed = float(L_ref)

    widths = np.diff(edges_ref)
    q_mass = (p_ref * widths)
    q_mass /= max(q_mass.sum(), 1e-300)

    theta_ref_ext = (be_ref, beA_ref, bm_ref, L_ref, Mc_ref, s_ref, 0.0)

    def _wmean_std(x, w):
        W = max(w.sum(), 1e-300)
        m = float(np.dot(w, x) / W)
        v = float(np.dot(w, (x - m) ** 2) / W)
        return m, math.sqrt(max(v, 1e-300))

    def objective(x):
        be_p, bm_p = map(float, x[:2])
        theta_prime_ext = (be_p, float(epsA_fixed), bm_p, float(L_fixed),
                           0.0, s_ref, 0.0)

        w, Mprime = reweight_from_samples_counts_with_s(
            M_ref=rho - s_ref * u, C=C, Ca=Ca, N=N,
            theta_prime=theta_prime_ext, theta_ref=theta_ref_ext,
            rho=rho, u=u, return_Mprime=True)

        Mc_w, std_w = _wmean_std(Mprime, w)
        std_w = max(std_w, 1e-300)
        x_vals = (Mprime - Mc_w) / std_w

        _, p_mass, sigma2_mass, nonempty = weighted_hist_and_sigma(
            x_vals, w, edges_ref, return_nonempty=True)

        m = (p_mass > 0) | (q_mass > 0)
        return js_div(q_mass[m], p_mass[m])

    return objective


def optimize_eps_mu_Mc_fixed_epsA_fixed_s(theta_ref, epsA_fixed,
                                          rho, u, C, Ca, N, edges_ref, p_ref,
                                          *, L_fixed=None, x0=None,
                                          bounds=None, options=None,
                                          eps_halfwidth=0.02,
                                          mu_halfwidth=0.02):
    """Verbatim from the notebooks (L-BFGS-B on the JS objective).

    The only change is that the +-0.02 box around the reference is now named
    (eps_halfwidth / mu_halfwidth) instead of hard-coded, so the caller can
    widen it when the eps_d step is larger than the notebook's 0.02.
    """
    obj = make_objective_fixed_epsA_fixed_s_with_sweights(
        theta_ref, epsA_fixed, rho, u, C, Ca, N, edges_ref, p_ref,
        L_fixed=L_fixed)
    be_ref, beA_ref, bm_ref, L_ref, Mc_ref, s_ref = _parse_theta_with_s(theta_ref)
    if L_fixed is None:
        L_fixed = L_ref

    if x0 is None:
        x0 = np.array([be_ref, bm_ref], float)

    if bounds is None:
        bounds = [(be_ref - eps_halfwidth, be_ref + eps_halfwidth),
                  (bm_ref - mu_halfwidth, bm_ref + mu_halfwidth)]

    res = minimize(obj, x0=np.asarray(x0, float), method="L-BFGS-B",
                   bounds=bounds, options=options or dict(maxiter=400,
                                                          ftol=1e-5))
    be_p, bm_p = map(float, res.x)

    theta_ref_ext = (be_ref, beA_ref, bm_ref, L_ref, Mc_ref, s_ref, 0.0)
    theta_prime_ext = (be_p, float(epsA_fixed), bm_p, float(L_fixed), 0.0,
                       s_ref, 0.0)
    w, Mprime = reweight_from_samples_counts_with_s(
        M_ref=rho - s_ref * u, C=C, Ca=Ca, N=N,
        theta_prime=theta_prime_ext, theta_ref=theta_ref_ext,
        rho=rho, u=u, return_Mprime=True)
    W = max(w.sum(), 1e-300)
    Mc_w = float(np.dot(w, Mprime) / W)

    res.theta_star = (be_p, float(epsA_fixed), bm_p, float(L_fixed), Mc_w,
                      float(s_ref))
    res.objective = obj
    res.bounds = bounds
    return res


def s_admissible_range(rho, u, *, frac=0.5, s_bound=5.0):
    """The branch of s on which M = rho - s*u is a usable order parameter.

    rho and u are very strongly anticorrelated at coexistence -- measured
    corr = -0.997 at L=10 and -0.999 at L=20 for the bent system at
    eps_d = 1.8 -- because both count particle contacts.  So

        Var(M)(s) = Var(rho) - 2 s Cov(rho,u) + s^2 Var(u)

    has a minimum at s* = Cov(rho,u)/Var(u) where M very nearly vanishes:
    sigma(M)/sigma(rho) bottoms out at 0.075 (L=10) and 0.045 (L=20), at
    s* ~ -0.25 in both cases.

    That point is a singularity of the fit objective, and it matters because
    the objective standardises M and symmetrises the result.  On the far side
    of s*, M has flipped sign relative to rho, and a sign-flipped order
    parameter can score *better* than the physical one -- which is exactly
    what happens at L=10, where the objective's global minimum sits at
    s = -0.325, past the degeneracy, while the physical branch contains s = 0.

    Returns the connected interval containing s = 0 on which
    sigma(M) >= frac * sigma(rho).
    """
    rho = np.asarray(rho, float).ravel()
    u = np.asarray(u, float).ravel()
    vr = float(np.var(rho))
    vu = float(np.var(u))
    cov = float(np.mean((rho - rho.mean()) * (u - u.mean())))
    lo, hi = -float(s_bound), float(s_bound)
    if vu <= 0 or vr <= 0:
        return lo, hi, float("nan"), float("nan")

    s_sing = cov / vu
    sig_min = math.sqrt(max(vr - cov * cov / vu, 0.0)) / math.sqrt(vr)

    # solve Var(M)(s) = frac^2 Var(rho)
    a, b, c = vu, -2.0 * cov, vr * (1.0 - frac * frac)
    disc = b * b - 4 * a * c
    if disc > 0:
        r1 = (-b - math.sqrt(disc)) / (2 * a)
        r2 = (-b + math.sqrt(disc)) / (2 * a)
        blo, bhi = min(r1, r2), max(r1, r2)
        if blo < 0.0 < bhi:
            # 0 itself is inside the degenerate band: nothing is admissible.
            return float("nan"), float("nan"), s_sing, sig_min
        if bhi <= 0.0:
            lo = bhi
        else:
            hi = blo
    return lo, hi, s_sing, sig_min


def profile_s(rho, u, x_ref, P_ref, *, s_grid=None, sigma_x=0.03,
              r_penalty=1e-1, w_asym=2.0, weights=None):
    """Profile the mixed-field fit objective over s.

    Worth knowing before reading the result: in the notebook's
    `fit_s_r_from_reweighted`, r does NOT enter `build_x_pdf` at all -- it
    appears only through the `r_penalty * r**2` term.  So the optimum is always
    r = 0, Lambda = 1 - s*r is always 1 (which is what the logged theta* records
    show), and the objective is a function of s ALONE.  This one-dimensional
    profile is therefore the complete picture of that fit, not a slice through
    it.

    Returns the objective and its two parts, plus P(x) at each s, so a caller
    can see whether a fitted s sits in a real minimum or on a plateau.
    """
    rho = np.asarray(rho, float).ravel()
    u = np.asarray(u, float).ravel()
    x_ref = np.asarray(x_ref, float).ravel()
    P_ref = np.asarray(P_ref, float).ravel()
    if s_grid is None:
        s_grid = np.linspace(-1.0, 1.0, 161)
    s_grid = np.asarray(s_grid, float)

    if weights is None:
        w = np.ones_like(rho, float)
    else:
        w = np.asarray(weights, float).ravel()
        w = np.where(np.isfinite(w) & (w > 0), w, 0.0)
    w /= max(w.sum(), 1e-300)

    obj = np.empty(s_grid.size)
    match = np.empty(s_grid.size)
    asym = np.empty(s_grid.size)
    P_all = np.empty((s_grid.size, x_ref.size))

    for i, s in enumerate(s_grid):
        M = rho - float(s) * u
        m = _wmean(M, w)
        sd = max(_wstd(M, w), 1e-300)
        P_est = _kde_fixed_sigma_on_grid((M - m) / sd, x_ref, sigma_x, w)
        d = P_est - P_ref
        match[i] = float(_trapz(d * d, x_ref))
        P_mir = np.interp(-x_ref, x_ref, P_est)
        A = 0.5 * (P_est - P_mir)
        asym[i] = float(_trapz(A * A, x_ref))
        obj[i] = match[i] + w_asym * asym[i]
        P_all[i] = P_est

    return dict(s_grid=s_grid, obj=obj, match=match, asym=asym, P=P_all,
                x=x_ref, P_ref=P_ref)


def equal_area_mu_reweight(rho, C, Ca, N, u, theta_ref, eps_new, epsA_fixed,
                           s_ref, L_fixed, dilute_window, dense_window,
                           mu_lo, mu_hi, tol=1e-4, max_iter=60):
    """mu that balances the two basins at eps_new, by reweighting alone.

    The scan must not be free to choose mu.  The standardised variable has zero
    mean by construction, so p_L*|c_L| = p_R*|c_R| identically: if the basins
    carry unequal weight, the lighter peak is pushed outward, the distribution
    looks asymmetric, and JS reports a mismatch that is arithmetic rather than
    physics.  Measured at eps_d = 1.8: 0.503/0.497 at L=10 against 0.525/0.475
    at L=20, which was the entire dense-peak displacement.

    Costs nothing -- it is a bisection over the same importance weights the
    objective already forms.
    """
    be_ref, beA_ref, bm_ref, _, Mc_ref, _ = _parse_theta_with_s(theta_ref)
    theta_ref_ext = (be_ref, beA_ref, bm_ref, L_fixed, Mc_ref, s_ref, 0.0)
    rho = np.asarray(rho, float)
    dil = (rho >= dilute_window[0]) & (rho < dilute_window[1])
    den = (rho >= dense_window[0]) & (rho <= dense_window[1])

    def imbalance(mu):
        w = reweight_from_samples_counts_with_s(
            M_ref=None, C=C, Ca=Ca, N=N,
            theta_prime=(eps_new, float(epsA_fixed), mu, float(L_fixed), 0.0,
                         s_ref, 0.0),
            theta_ref=theta_ref_ext, rho=rho, u=u)
        W = max(w.sum(), 1e-300)
        return float(w[den].sum() / W - w[dil].sum() / W)

    lo, hi = float(mu_lo), float(mu_hi)
    f_lo, f_hi = imbalance(lo), imbalance(hi)
    # mu enters as an occupancy penalty, so imbalance decreases with mu; widen
    # the bracket if the requested window does not contain the root.
    for _ in range(8):
        if f_lo * f_hi <= 0:
            break
        span = hi - lo
        lo -= span
        hi += span
        f_lo, f_hi = imbalance(lo), imbalance(hi)
    if f_lo * f_hi > 0:
        return float(bm_ref), False
    for _ in range(max_iter):
        mid = 0.5 * (lo + hi)
        f = imbalance(mid)
        if abs(f) < tol:
            return float(mid), True
        if f * f_lo > 0:
            lo, f_lo = mid, f
        else:
            hi, f_hi = mid, f
    return float(0.5 * (lo + hi)), True


def scan_eps_mu_fixed_epsA_fixed_s(theta_ref, epsA_fixed,
                                   rho, u, C, Ca, N, edges_ref, p_ref, *,
                                   L_fixed=None, eps_halfwidth=0.02,
                                   mu_halfwidth=0.02, n_eps=81, n_mu=41,
                                   smooth_pts=7, fit_pts=9, ess_floor=0.0,
                                   mu_mode="equal-area",
                                   dilute_window=(0.0, 0.4),
                                   dense_window=(0.6, 1.0),
                                   verbose=False):
    """Grid scan of the SAME objective, used only to rescue stalled steps.

    L-BFGS-B on a piecewise-constant objective can terminate at its starting
    point (mc_fss FINDINGS 4.1).  In continuation mode that shows up as a step
    where eps_nd does not move at all -- which is what produced the runs of
    3-4 frozen entries in the logged bent-geometry trace.  When --scan-fallback
    is on, such a step is redone here: profile JS over eps at the best mu, then
    fit a local parabola to the minimum.
    """
    be_ref, beA_ref, bm_ref, L_ref, Mc_ref, s_ref = _parse_theta_with_s(theta_ref)
    if L_fixed is None:
        L_fixed = L_ref
    obj = make_objective_fixed_epsA_fixed_s_with_sweights(
        theta_ref, epsA_fixed, rho, u, C, Ca, N, edges_ref, p_ref,
        L_fixed=L_fixed)

    eps_grid = np.linspace(be_ref - eps_halfwidth, be_ref + eps_halfwidth,
                           int(n_eps))
    mu_grid = np.linspace(bm_ref - mu_halfwidth, bm_ref + mu_halfwidth,
                          int(n_mu))

    prof = np.empty(eps_grid.size)
    mu_at = np.empty(eps_grid.size)
    n_ea_fail = 0
    for i, e in enumerate(eps_grid):
        if mu_mode == "equal-area":
            m_ea, ok_ea = equal_area_mu_reweight(
                rho, C, Ca, N, u, theta_ref, e, epsA_fixed, s_ref, L_fixed,
                dilute_window, dense_window, mu_grid[0], mu_grid[-1])
            n_ea_fail += int(not ok_ea)
            mu_at[i] = m_ea
            prof[i] = obj([e, m_ea])
        else:
            vals = np.array([obj([e, m]) for m in mu_grid])
            j = int(np.argmin(vals))
            prof[i] = vals[j]
            mu_at[i] = mu_grid[j]
    if verbose and mu_mode == "equal-area" and n_ea_fail:
        print(f"[scan] equal-area mu could not be bracketed at "
              f"{n_ea_fail}/{eps_grid.size} grid points", flush=True)

    # ESS along the profile, computed BEFORE the minimum is chosen.  This is
    # what makes a wide window safe: scan far enough to contain the
    # displacement, then refuse to pick a minimum from the part of the window
    # where the reweighting is carried by a handful of configurations.
    theta_ref_ext = (be_ref, beA_ref, bm_ref, L_ref, Mc_ref, s_ref, 0.0)
    n = np.asarray(rho, float).size
    ess = np.empty(eps_grid.size)
    for i, (e, m) in enumerate(zip(eps_grid, mu_at)):
        w = reweight_from_samples_counts_with_s(
            M_ref=None, C=C, Ca=Ca, N=N,
            theta_prime=(e, float(epsA_fixed), m, float(L_fixed), 0.0,
                         s_ref, 0.0),
            theta_ref=theta_ref_ext, rho=rho, u=u)
        ess[i] = _ess(w) / max(n, 1)

    ok = ess >= float(ess_floor)
    if not ok.any():
        ok = np.ones_like(ess, dtype=bool)
    frac_ok = float(np.mean(ok))

    # light smoothing, then a local quadratic around the discrete minimum
    k = max(1, int(smooth_pts) | 1)
    if k > 1 and prof.size > k:
        ker = np.ones(k) / k
        sm = np.convolve(np.pad(prof, (k // 2, k // 2), mode="edge"), ker,
                         mode="valid")
    else:
        sm = prof
    i0 = int(np.argmin(np.where(ok, sm, np.inf)))

    # Is the chosen point at an edge of the ADMISSIBLE region?  That is the
    # honest "no interior minimum" test -- the raw window edge is not, once
    # part of the window has been masked away.
    idx_ok = np.flatnonzero(ok)
    at_edge = bool(i0 <= idx_ok[0] or i0 >= idx_ok[-1])

    lo = max(int(idx_ok[0]), i0 - int(fit_pts) // 2)
    hi = min(int(idx_ok[-1]) + 1, i0 + int(fit_pts) // 2 + 1)
    eps_star = float(eps_grid[i0])
    curvature = float("nan")
    if hi - lo >= 3 and not at_edge:
        c = np.polyfit(eps_grid[lo:hi], sm[lo:hi], 2)
        if c[0] > 0:
            cand = -0.5 * c[1] / c[0]
            if eps_grid[lo] <= cand <= eps_grid[hi - 1]:
                eps_star = float(cand)
                curvature = float(2.0 * c[0])
    mu_star = float(np.interp(eps_star, eps_grid, mu_at))
    js_star = float(obj([eps_star, mu_star]))

    if verbose:
        print(f"[scan] eps*={eps_star:.6f} mu*={mu_star:.6f} JS={js_star:.5f} "
              f"curv={curvature:.3g}  ESS/n at min "
              f"{np.interp(eps_star, eps_grid, ess):.2f}  "
              f"window admissible {100 * frac_ok:.0f}% "
              f"(ESS/n >= {ess_floor:g})"
              f"{'  AT ADMISSIBLE EDGE' if at_edge else ''}", flush=True)

    return dict(eps_nd=eps_star, mu=mu_star, js=js_star,
                curvature=curvature, eps_grid=eps_grid, prof=prof,
                mu_at=mu_at, ess=ess, admissible=ok, frac_admissible=frac_ok,
                at_edge=at_edge)


# --- mu search by simulation ------------------------------------------------
def find_mu_equal_areas_by_simulation(simulate, mu0,
                                      dilute_window=(0.00, 0.30),
                                      dense_window=(0.70, 1.00),
                                      step0=0.02, tol=2e-2, max_iters=50,
                                      verbose=True):
    """Verbatim from the notebooks, plus a geometric pre-bracket.

    The notebook's fixed-step search creeps at `step0` per iteration and cannot
    recover an O(1) error in mu inside its iteration cap.  Within a
    continuation that is fine -- mu moves by ~d(eps_d) per step -- but the very
    first step of a segment starts from an anchor measured at a different L,
    where the offset can be much larger.  The pre-bracket doubles the step
    until the sign of (m_dense - m_dilute) flips, then hands the bracket to the
    original bisection.
    """
    def basin_masses(rho):
        rho = np.asarray(rho, float)
        m_dil = ((rho >= dilute_window[0]) & (rho < dilute_window[1])).mean()
        m_den = ((rho >= dense_window[0]) & (rho <= dense_window[1])).mean()
        return float(m_dil), float(m_den)

    cache = {}

    def mass_diff_at(mu):
        mu = float(mu)
        mu_key = float(np.round(mu, 12))
        if mu_key in cache:
            return cache[mu_key]
        data = simulate(mu)
        m_dil, m_den = basin_masses(data.rho_mu)
        f = float(m_den - m_dil)
        cache[mu_key] = (f, data)
        return cache[mu_key]

    mu = float(mu0)
    f, data = mass_diff_at(mu)
    if verbose:
        print(f"[mu={mu:.6f}] f=m_dense-m_dilute={f:+.4f}", flush=True)

    best = (abs(f), mu, data)
    bracket = None

    # --- geometric pre-bracket ------------------------------------------
    if abs(f) > tol:
        step = float(step0)
        for _ in range(12):
            mu_try = mu + (step if f > 0 else -step)
            f_try, d_try = mass_diff_at(mu_try)
            if verbose:
                print(f"[pre-bracket] mu={mu_try:.6f} f={f_try:+.4f} "
                      f"step={step:.4f}", flush=True)
            if abs(f_try) < best[0]:
                best = (abs(f_try), mu_try, d_try)
            if abs(f_try) <= tol:
                return {"mu": mu_try, "success": True, "data": d_try,
                        "iters": 0, "n_sim": len(cache)}
            if f * f_try < 0.0:
                bracket = ((mu, f, mu_try, f_try) if f < 0
                           else (mu_try, f_try, mu, f))
                break
            step *= 2.0
        # If no flip was found the loop falls through to the original walk.

    for it in range(1, int(max_iters) + 1):
        if abs(f) <= tol:
            return {"mu": mu, "success": True, "data": data, "iters": it - 1,
                    "n_sim": len(cache)}

        if bracket is not None:
            mu_lo, f_lo, mu_hi, f_hi = bracket
            mu = 0.5 * (mu_lo + mu_hi)
            f, data = mass_diff_at(mu)
            if verbose:
                print(f"[bisect] mu={mu:.6f} f={f:+.4f} "
                      f"bracket=[{mu_lo:.6f},{mu_hi:.6f}]", flush=True)
            if abs(f) < best[0]:
                best = (abs(f), mu, data)
            if f < 0:
                bracket = (mu, f, mu_hi, f_hi)
            else:
                bracket = (mu_lo, f_lo, mu, f)
            continue

        mu_new = mu + (step0 if f > 0 else -step0)
        f_new, data_new = mass_diff_at(mu_new)
        if verbose:
            print(f"[step] mu={mu_new:.6f} f={f_new:+.4f}", flush=True)

        if abs(f_new) < best[0]:
            best = (abs(f_new), mu_new, data_new)

        if f != 0.0 and f_new != 0.0 and (f * f_new < 0.0):
            bracket = ((mu, f, mu_new, f_new) if f < 0
                       else (mu_new, f_new, mu, f))

        mu, f, data = mu_new, f_new, data_new

    _, mu_best, data_best = best
    return {"mu": mu_best, "success": False, "data": data_best,
            "iters": int(max_iters), "n_sim": len(cache)}


